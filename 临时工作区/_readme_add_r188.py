def insert_after(lines, anchor_sub, new_lines, expect=1):
    """在包含 anchor_sub 的行后插入 new_lines；返回 (新 lines, 命中数)。"""
    hits = [i for i, ln in enumerate(lines) if anchor_sub in ln]
    if len(hits) != expect:
        raise SystemExit("ANCHOR ERROR: %r hits=%d (expect %d)"
                         % (anchor_sub[:60], len(hits), expect))
    out = []
    for i, ln in enumerate(lines):
        out.append(ln)
        if i == hits[0]:
            out.extend(new_lines)
    return out, len(hits)


