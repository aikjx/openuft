# 约定 μ dg/dμ = -b0 g^3/(16π^2)；解 1/g²(μ)=1/g²(μ0)+ b0/(8π²) ln(μ/μ0)
def g_run(g0, mu0, mu, b0):
    inv = 1.0/g0**2 + b0/(8*math.pi**2)*math.log(mu/mu0)
    return 1/math.sqrt(inv) if inv > 0 else float('nan')
