# ============================================================
# [0] 公理基底回顾 (21号已证, 此处仅引用)
# ============================================================
sec("[0] 基底: α=τ/κ 公理 + 归一化母方程 (21/19号已证)")
put(f"  实测 α_inv = {nstr(ALPHA_INV,12)}  ⇒  α = {nstr(ALPHA,12)}")
put(f"  归一化母方程 κ̃²+τ̃²=1, κ̃=1/√(1+α²), τ̃=α/√(1+α²)  (19号机器零✓)")
kappa_tilde = 1/sqrt(1+ALPHA**2)
tau_tilde   = ALPHA/sqrt(1+ALPHA**2)
put(f"    κ̃={nstr(kappa_tilde,10)}, τ̃={nstr(tau_tilde,12)}, κ̃²+τ̃²={nstr(kappa_tilde**2+tau_tilde**2,6)}")
put(f"  α=τ/κ 公理地位: 区间 α∈(0,1], 电子处极弱扭转区 κ≫τ")

# ============================================================
# [1] 级联投影公式的机器零闭包
# ============================================================
sec("[1] 级联投影 α=tan(k·atan(α0)) 的机器零闭包")
put(f"  几何假设: 主螺旋挠率 τ 由 k 级子螺旋净投影, 每级基础扭转 α0")
put(f"    净投影: α = tan( k · atan(α0) )   (k 级整数级联, α0≪1 时 ≈ k·α0)")
put(f"  验证闭包: 给定实测 α, 反解 α0=tan(atan(α)/k), 再还原 α'=tan(k·atan(α0))")
# 用一组候选级联数 k 测试闭包
for k in [1, 2, 3, 7, 11, 137]:
    alpha0 = tan(atan(ALPHA)/k)
    alpha_back = tan(k*atan(alpha0))
    r = rel(alpha_back, ALPHA)
    put(f"    k={k:4d}: α0={nstr(alpha0,10)} 还原α'={nstr(alpha_back,12)} 残差={nstr(r,3)} -> {'PASS' if r<mpf('1e-45') else 'FAIL'}")
put(f"  [结论] 对任意整数 k, 级联投影公式 α=tan(k·atan(α0)) 精确闭包 (机器零),")
put(f"          因它只是 α=τ/κ 在'k级均匀扭转'下的重参数化 — 数学恒等, 非物理派生")

# ============================================================
# [2] 基础扭转 α0 的几何意义 — k=137 的特殊性
# ============================================================
sec("[2] 基础扭转 α0: k=137 时 α0 的几何解读")
# 若取 k = round(1/α) = 137 (21号'137圈=一整圈电磁扭转')
