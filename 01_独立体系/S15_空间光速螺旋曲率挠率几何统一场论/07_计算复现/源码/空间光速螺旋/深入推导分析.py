import math

# CODATA 2022
class CODATA:
    c = 299792458.0
    h = 6.62607015e-34
    hbar = h / (2 * math.pi)
    G = 6.67430e-11
    e = 1.602176634e-19
    alpha = 7.2973525693e-03
    eps0 = 8.8541878128e-12
    m_e = 9.1093837015e-31
    m_p = 1.67262192369e-27
    
    @classmethod
    def l_P(cls):
        return math.sqrt(cls.hbar * cls.G / cls.c**3)
    
    @classmethod
    def m_P(cls):
        return math.sqrt(cls.hbar * cls.c / cls.G)


cd = CODATA
c = cd.c
hbar = cd.hbar
G = cd.G
e = cd.e
alpha = cd.alpha
eps0 = cd.eps0
m_e = cd.m_e
m_p = cd.m_p
