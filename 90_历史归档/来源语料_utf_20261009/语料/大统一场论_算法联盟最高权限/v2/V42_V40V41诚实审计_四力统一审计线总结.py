def frenet_kappa_tau(r_func, t0):
    """用 mpmath.diff 高精度数值微分计算 Frenet 曲率 κ 和挠率 τ.
    r_func: t -> (x, y, z) 三元组函数
    返回 (kappa, tau)."""
    # 各分量在各阶导数
    rp   = [diff(lambda t, i=i: r_func(t)[i], t0, 1) for i in range(3)]
    rpp  = [diff(lambda t, i=i: r_func(t)[i], t0, 2) for i in range(3)]
    rppp = [diff(lambda t, i=i: r_func(t)[i], t0, 3) for i in range(3)]
    # r' × r''
    cross = [
        rp[1]*rpp[2] - rp[2]*rpp[1],
        rp[2]*rpp[0] - rp[0]*rpp[2],
        rp[0]*rpp[1] - rp[1]*rpp[0],
    ]
    cross_norm_sq = sum(x**2 for x in cross)
    rp_norm = sqrt(sum(x**2 for x in rp))
    kappa = sqrt(cross_norm_sq) / rp_norm**3
    # τ = (r' × r'') · r''' / |r' × r''|²
    triple = sum(cross[i] * rppp[i] for i in range(3))
    tau = triple / cross_norm_sq
    return kappa, tau

