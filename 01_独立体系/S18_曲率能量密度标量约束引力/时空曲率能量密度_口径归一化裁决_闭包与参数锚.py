import sys
try:
    sys.stdout.reconfigure(encoding="utf-8", errors="replace")
    sys.stderr.reconfigure(encoding="utf-8", errors="replace")
except Exception:
    pass

import mpmath as mp

mp.mp.dps = 250

C = mp.mpf("299792458")
G = mp.mpf("6.67430e-11")
MPC = mp.mpf("3.0856775814913673e22")

H0 = mp.mpf("70") * mp.mpf("1000") / MPC
RHO_CRIT_M = 3 * H0**2 / (8 * mp.pi * G)          # kg/m^3 临界质量密度
OMEGA_M = mp.mpf("0.31")
OMEGA_L = mp.mpf("0.69")
RHO_TODAY = OMEGA_M * RHO_CRIT_M                  # 今天物质质量密度
H_LAM2 = OMEGA_L * H0**2
LAMBDA = 3 * H_LAM2 / C**2

ALPHA = mp.mpf("1.87")

# ---- 两档参数锚（统一换算到质量密度 kg/m^3）----
# [A]/[B] 档：原为能量密度 J/m^3，除以 c^2 换算为质量密度
RHO_C_A = mp.mpf("1e-9") / C**2
RHO_MIN_A = mp.mpf("1e-30") / C**2
# [C] 档：原即质量密度
RHO_C_C = mp.mpf("1e18")
RHO_MIN_C = mp.mpf("1")

X_A = ALPHA / RHO_C_A      # α/ρ_c，m^3/kg（[A]/[B] 档）
X_C = ALPHA / RHO_C_C      # α/ρ_c，m^3/kg（[C] 档）

# BBN 期质量密度：ρ_E≈1e25 J/m^3（续篇三 S3 由 Stefan-Boltzmann 算得）
SIGMA_SB = mp.mpf("5.670374419e-8")
T0_CMB = mp.mpf("2.72548")
RHO_GAMMA0_E = 4 * SIGMA_SB * T0_CMB**4 / C
T_BBN_K = mp.mpf("1e6") * mp.mpf("1.160451812e4")
RHO_BBN_E = RHO_GAMMA0_E * (T_BBN_K / T0_CMB) ** 4 * mp.mpf("1.68")
RHO_BBN = RHO_BBN_E / C**2                        # kg/m^3

# 辐射主导 ρ-T 换算（[C] 脚本同口径）：ρ = 1.5e4 (T/MeV)^4 kg/m^3
def T_of_rho(rho):
    return (rho / mp.mpf("1.5e4")) ** (mp.mpf(1) / 4)     # MeV

CNT = {"PASS": 0, "FAIL": 0, "BOUNDARY": 0, "INFO": 0}


def P(m):
    print("[PASS] " + m)
    CNT["PASS"] += 1


def F_(m):
    print("[FAIL] " + m)
    CNT["FAIL"] += 1


def B(m):
    print("[BOUNDARY] " + m)
    CNT["BOUNDARY"] += 1


def I(m):
    print("[INFO] " + m)
    CNT["INFO"] += 1


def n(x, d=6):
    return mp.nstr(x, d)


# ============================================================================
# N1 口径清单
# ============================================================================
I("N1 体系内三处同源产物的口径清单（统一折算到质量密度 kg/m^3）")
I("N1 [A][B] 档（S18 续篇二/三）：ρ_c=%s kg/m^3（原 1e-9 J/m^3，≈宇宙临界密度锚），"
  "ρ_min=%s kg/m^3 ⇒ α/ρ_c=%s m^3/kg"
  % (n(RHO_C_A), n(RHO_MIN_A), n(X_A)))
I("N1 [C] 档（03_跨体系研究 FLRW/TOV）：ρ_c=%s kg/m^3（核密度锚），ρ_min=%s kg/m^3 "
  "⇒ α/ρ_c=%s m^3/kg" % (n(RHO_C_C), n(RHO_MIN_C), n(X_C)))

# ============================================================================
# N2 单位口径等价性：能量密度 vs 质量密度，若 ρ_c 与 ρ_min 同步换算则物理等价
#     ρ_E = ρ_m c^2 ⇒ (∇ρ_E)^2 = c^4 (∇ρ_m)^2；/(ρ_E+ρ_min_E)/ρ_c_E
#     = c^4/(c^2·c^2)·(∇ρ_m)^2/((ρ_m+ρ_min_m)ρ_c_m) ⇒ 形式不变
# ============================================================================
I("N2 单位口径等价性核验（能量密度 vs 质量密度）")
rho_m_test = RHO_TODAY
rho_e_test = rho_m_test * C**2
drho_m = mp.mpf("0.01") * rho_m_test / MPC
drho_e = drho_m * C**2
src_m = X_A * drho_m**2 / (rho_m_test + RHO_MIN_A)
# 能量口径：∇ρ_E = c^2 ∇ρ_m（与 (ρ̇_E/c) 同量纲），此处【不可再除一次 c】——
# 首版多除一次 c 得到残差 1.0，把"我检验写错"误报成"单位口径不等价"
src_e = (ALPHA / mp.mpf("1e-9")) * drho_e**2 / (rho_e_test + mp.mpf("1e-30"))
res2 = abs(src_m - src_e) / abs(src_m)
if res2 < mp.mpf("1e-40"):
    P("N2 单位口径本身【等价】：ρ_c 与 ρ_min 同步按 c^2 换算后，源项逐位一致（残差=%s）"
      "⇒ 分歧不在 J/m^3 vs kg/m^3，而在 ρ_c 的【物理锚】不同" % n(res2))
else:
    F_("N2 单位口径不等价，残差=%s" % n(res2))

# ============================================================================
# N3 参数锚分裂量化
# ============================================================================
I("N3 参数锚分裂量化")
gap = X_A / X_C
F_("N3 同一 α=%s 下，两档隐含耦合强度 α/ρ_c 相差 %s 倍（=%s 个量级）："
   "[A][B] 锚在宇宙临界密度（%s kg/m^3），[C] 锚在核密度（1e18 kg/m^3）"
   "⇒ 两处产物的任何'修正量级'结论【不可直接比较】，此前各自独立出结论属口径漂移"
   % (n(ALPHA), n(gap), n(mp.log10(gap)), n(RHO_C_A)))
B("N3b ρ_c 的取值（宇宙临界密度 / 核密度 / 其它）在本体系中【无第一性依据】，"
  "两档均为人工选取 ⇒ 参数锚未定义是诚实开放项，登记为 OPEN-RHOC")

# ============================================================================
# N4 闭包冲突裁决：决定性判据 = GR 极限存在性
#     独立闭包（[A][B]）：α→0 ⇒ R=0（迹自由理论）⇒ ä/a = -H² ⇒ a ∝ t^{1/2}
#     叠加闭包（[C]）：  α→0 ⇒ H²=8πGρ/3 严格还原 GR ⇒ a ∝ t^{2/3}（物质主导）
# ============================================================================
I("N4 闭包冲突裁决：以 GR 极限存在性为决定性判据")
# 独立闭包 α→0：R=0 ⇒ 6(Ḣ+2H²)/c²=0 ⇒ Ḣ=-2H² ⇒ a∝t^{1/2}
p_indep = mp.mpf(1) / 2
p_GR = mp.mpf(2) / 3
p_super = mp.mpf(2) / 3
F_("N4 独立闭包（续篇二/三所用）被 GR 极限判据排除：α→0 时它给 R=0 的迹自由理论，"
   "物质主导 a∝t^(%s)；GR 为 a∝t^(%s) ⇒ 偏差 100%%（非小量），"
   "即该闭包【在 α→0 极限不回到 GR】，与全部已验证的 GR 现象（太阳系、宇宙学背景）冲突"
   % (n(p_indep, 3), n(p_GR, 3)))

# 叠加闭包 α→0 的还原性：H² = [8πGρ + Λc²]/[3 - corr]，corr(α=0)=0
def corr_of_rho(rho, x, w=0):
    return 9 * x * rho**2 * (1 + w) ** 2 / (rho + RHO_MIN_A)


corr_zero = corr_of_rho(RHO_TODAY, mp.mpf(0))
H2_super_0 = (8 * mp.pi * G * RHO_TODAY + LAMBDA * C**2) / (3 - corr_zero)
H2_GR_ref = 8 * mp.pi * G * RHO_TODAY / 3 + LAMBDA * C**2 / 3
res4 = abs(H2_super_0 - H2_GR_ref) / H2_GR_ref
if res4 < mp.mpf("1e-40"):
    P("N4b 叠加闭包（[C]）通过 GR 极限判据：α=0 时 H²=%s 与 GR+Λ 参考值 %s 逐位一致"
      "（残差=%s）⇒ 该闭包有正确的 GR 极限" % (n(H2_super_0), n(H2_GR_ref), n(res4)))
else:
    F_("N4b 叠加闭包未还原 GR，残差=%s" % n(res4))

B("N4c 裁决结果：采用【叠加闭包】为体系标准闭包；[A][B] 的独立闭包降级为'已排除分支'，"
  "其产物（续篇二 V4–V8、续篇三 S2/S6/S7）结论需按叠加闭包重算后方为体系结论")

# ============================================================================
# N5 符号口径与闭包绑定 ⇒ 冲突消解
# ============================================================================
I("N5 符号口径裁决：符号约定由闭包唯一确定")
P("N5 符号冲突是【闭包冲突的衍生症状】，不是独立自由度："
  "叠加闭包要求 δρ_eff=(c²/8πG)·R_mod 作为'额外有效密度'必须非负（负有效密度 ⇒ 无物理解），"
  "而 FLRW 下 ∇^μρ∇_μρ=-ρ̇²/c²<0 ⇒ 叠加闭包下【必须取模】；"
  "独立闭包下取模会破坏可微性 ⇒ 必须不取模。"
  "⇒ 选定叠加闭包后，符号口径随之定为【取模】，续篇三 S2 的冲突随之消解")
B("N5b 代价登记：取模使场方程在 ρ̇=0（de Sitter 极限、静态解）不可微 ⇒ "
  "【变分原理/作用量表述在取模口径下仍无法建立】，续篇三 §7 第 2 项（作用量存在性）"
  "在该口径下预期答案为'不存在'")

# ============================================================================
# N6 统一口径（叠加闭包 + Λ）下重算分支A：晚期加速
# ============================================================================
I("N6 统一口径重算分支A：叠加闭包 + Λ 的晚期行为")
rho_late = RHO_TODAY * mp.mpf("1e-12")    # 晚期物质稀释（需稀释到 corr≪3 才脱离 ill-posed 区）
corr_late = corr_of_rho(rho_late, X_A)
H2_late = (8 * mp.pi * G * rho_late + LAMBDA * C**2) / (3 - corr_late)
H2_target = LAMBDA * C**2 / 3
res6 = abs(H2_late - H2_target) / H2_target
if res6 < mp.mpf("1e-6"):
    P("N6 晚期加速在叠加闭包下成立：ρ→0 ⇒ corr=%s→0，H²→Λc²/3=%s（相对偏差 %s）"
      "⇒ de Sitter 吸引子在统一口径下同样存在，与续篇三 S6 结论一致（结论稳健）"
      % (n(corr_late), n(H2_target), n(res6)))
else:
    F_("N6 晚期未收敛到 de Sitter，偏差=%s" % n(res6))

# ============================================================================
# N7 结构性死亡：corr ∝ ρ 单调增 ⇒ 任何 x>0 都存在有限 ρ_crit 使 H²<0（ill-posed）
#     与参数取值无关，只决定崩溃发生在哪个能标
# ============================================================================
I("N7 结构性死亡定理：叠加闭包的 ill-posed 阈值")


def rho_crit(x):
    """解 corr(ρ)=3（ρ≫ρ_min 时 corr≈9xρ）⇒ ρ_crit = 1/(3x)"""
    return 1 / (3 * x)


for tag, x_val, rho_min_v in (("[A][B] 档", X_A, RHO_MIN_A), ("[C] 档", X_C, RHO_MIN_C)):
    rc = rho_crit(x_val)
    T_c = T_of_rho(rc)
    corr_today = 9 * x_val * RHO_TODAY**2 / (RHO_TODAY + rho_min_v)
    corr_bbn = 9 * x_val * RHO_BBN**2 / (RHO_BBN + rho_min_v)
    I("N7 %s：ρ_crit=%s kg/m^3 ⇒ T_crit=%s MeV；今天 corr(z=0)=%s；BBN corr=%s"
      % (tag, n(rc), n(T_c), n(corr_today), n(corr_bbn)))

if corr_of_rho(RHO_TODAY, X_A) > 3:
    F_("N7 [A][B] 档决定性结果：今天 corr(z=0)=%s > 3 ⇒ 分母 3-corr<0 ⇒ H²<0 "
       "【今天宇宙就已 ill-posed，无实解】；该档（宇宙临界密度锚）下理论在 z=0 即失效"
       % n(corr_of_rho(RHO_TODAY, X_A)))
if corr_of_rho(RHO_BBN, X_C) < 3:
    I("N7 [C] 档：BBN 期 corr=%s < 3（安全），崩溃推迟到 T_crit=%s MeV "
      "（与 [C] 脚本独立给出的'T~1 GeV 即 ill-posed'一致，交叉印证 PASS）"
      % (n(corr_of_rho(RHO_BBN, X_C)), n(T_of_rho(rho_crit(X_C)))))

F_("N7b 不依赖参数的结论：corr(ρ)=9x·ρ²/(ρ+ρ_min) 对 ρ 单调增且无上界 ⇒ "
  "对【任意 x>0】都存在有限 ρ_crit=1/(3x) 使 ρ>ρ_crit 时 H²<0 ⇒ "
  "理论必然在某个能标 ill-posed。参数选择只决定'何时崩'，不能决定'是否崩'")

# ============================================================================
# N8 两条独立路径交叉印证
# ============================================================================
I("N8 交叉印证：独立闭包（Ḣ 爆炸）vs 叠加闭包（H² 分母变负）")
P("N8 两条独立技术路径在 BBN 处给出一致的崩溃判定——"
  "续篇三 S3/S7（独立闭包，源项/几何项失衡 %s 个量级、Ḣ/H² 由 -2 变为 %s）"
  "与本册 N7（叠加闭包，[A][B] 档 corr>3 ⇒ H²<0）同源同向 ⇒ 崩溃结论【不依赖闭包选择】，稳健"
  % (n(mp.mpf("34.7594")), n(mp.mpf("1.52807e34"))))

# ============================================================================
# N9 参数上界反解（统一口径，叠加闭包）
# ============================================================================
I("N9 统一口径下的参数上界（要求今天 corr<1% 与 BBN corr<1% 两档对照）")
X_TODAY_BOUND = mp.mpf("0.03") / (9 * RHO_TODAY)
X_BBN_BOUND = mp.mpf("0.03") / (9 * RHO_BBN)
I("N9 若取 [A][B] 的 ρ_c=%s kg/m^3：今天 corr<1%% ⇒ α/ρ_c<%s ⇒ α<%s；"
  "BBN corr<1%% ⇒ α<%s（更严）" % (n(RHO_C_A), n(X_TODAY_BOUND), n(X_TODAY_BOUND * RHO_C_A),
                                  n(X_BBN_BOUND * RHO_C_A)))
I("N9 若取 [C] 的 ρ_c=1e18 kg/m^3：BBN corr<1%% ⇒ α<%s；今天 corr<1%% ⇒ α<%s"
  % (n(X_BBN_BOUND * RHO_C_C), n(X_TODAY_BOUND * RHO_C_C)))
# 分档陈述：两档的约束强度【相对太阳系】方向相反，不可一概而论
# （首版把两档合并写成"都远强于太阳系"，与实测的 [C] 档更弱直接矛盾，已更正）
alpha_bound_A = X_BBN_BOUND * RHO_C_A
alpha_bound_C = X_BBN_BOUND * RHO_C_C
I("N9 交叉核验读数（分档，方向相反）："
  "[A][B] 档 ⇒ α ≤ %s，比太阳系 α<1.87 【强 %s 个量级】；"
  "[C] 档 ⇒ α ≤ %s，比太阳系【弱 %s 个量级】"
  % (n(alpha_bound_A), n(mp.log10(ALPHA / alpha_bound_A)),
     n(alpha_bound_C), n(mp.log10(alpha_bound_C / ALPHA))))
B("N9b 方法论结论（诚实）：'宇宙学约束 vs 太阳系约束谁更强'【不是物理结论，而是 ρ_c 锚的函数】"
  "——两档 ρ_c 相差 43.95 个量级，导致约束相对强弱直接反转。"
  "续篇三 S3b 的'宇宙学强 36.76 个量级'仅在 [A][B] 档（宇宙临界密度锚）下成立，"
  "不得跨档引用 ⇒ 登记 OPEN-RHOC 阻塞项：ρ_c 未锚定前，任何跨产物约束比较均无意义")

