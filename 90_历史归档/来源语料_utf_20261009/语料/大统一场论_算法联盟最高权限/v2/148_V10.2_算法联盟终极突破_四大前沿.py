def search_integer_relations(targets, basis, max_coeff=20):
    """搜索 targets 与 basis 之间的低阶整数关系"""
    results = []
    for t_name, t_val in targets.items():
        for b_name, b_val in basis.items():
            # 搜索 a·t + b·basis = c (c是小整数)
            ratio = t_val / b_val
            # 检查 ratio 是否接近有理数 p/q
            for q in range(1, max_coeff+1):
                p = round(float(ratio * q))
                if p == 0: continue
                err = fabs(ratio - mpf(p)/q) / fabs(ratio)
                if err < 1e-10:
                    results.append((t_name, b_name, p, q, err))
    return results

