# dB_x/dθ = h·cosθ/L → dB_x/ds = hcosθ/L²
# dB_y/dθ = h·sinθ/L → dB_y/ds = hsinθ/L²
# N_x = -cosθ, N_y = -sinθ
# <dB/ds, N> = (hcosθ/L²)(-cosθ) + (hsinθ/L²)(-sinθ) = -h/L²(cos²θ+sin²θ) = -h/L²
