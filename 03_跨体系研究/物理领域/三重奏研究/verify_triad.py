sep("S1 公理A求导：由 u^μu_μ=c² 推出 加速度正交性 u_μa^μ=0（符号验证）")
# ----------------------------------------------------------------------
tau, c, a = sp.symbols('tau c a', positive=True)
# 双曲运动（匀固有加速）世界线：X^μ(τ)
tX = c**2/a * sp.sinh(a*tau/c)          # X^0
xX = c**2/a * sp.cosh(a*tau/c)          # X^1
U0 = sp.diff(tX, tau); U1 = sp.diff(xX, tau)
A0 = sp.diff(U0, tau); A1 = sp.diff(U1, tau)
u2  = sp.simplify(U0**2 - U1**2 - c**2)
uA  = sp.simplify(U0*A0 - U1*A1)
print("4速度归一化 u^μu_μ − c² =", u2, "  （应为 0）")
print("加速度正交性 u_μa^μ      =", uA, "  （应为 0）")
