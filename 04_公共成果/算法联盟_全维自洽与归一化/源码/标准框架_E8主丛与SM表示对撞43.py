higgs = 4                           # Higgs 二重态 4 实分量
sm_total = fermions + gauge + higgs
chk("SM 自由度计数", sm_total == 48+12+4,
    "三代费米子 48 + 规范 12 + Higgs 4 = %d" % sm_total)

# E8 中可用费米子位置（E6 链：(27,3) 与 (27̄,3̄)）
e8_fermion_slots = 27*3 + 27*3      # 162
chk("E8 费米子槽位", e8_fermion_slots == 162, "(27,3)+(27̄,3̄) = 162 个旋量位置")
redun = Fraction(e8_fermion_slots, fermions)
chk("E8 费米子冗余", redun == Fraction(162, 48), "162/48 = 27/8 = 3.375× 冗余")

# ============ 第 3 节：32 维流形旋量交叉引用（37 期） ============
# Cl(1,31) 的不可约旋量表示维数 = 2^(15) 复维 = 32768？规范结论：
# Cl(p,q) 复化旋量 = 2^floor((p+q)/2)；对 32 维 = 2^16 = 65536 实（或 2^15 复 = 32768 复）
cl_dim = 2**16
ratio_cl = Fraction(cl_dim, fermions)
