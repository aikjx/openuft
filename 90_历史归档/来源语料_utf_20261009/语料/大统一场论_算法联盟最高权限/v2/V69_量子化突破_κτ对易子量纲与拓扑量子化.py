# 数值求解 T = n 的α值
def solve_alpha_from_T(n_val):
    """求解 πα/(1+α²)² = n 的α"""
    # (1+α²)² = πα/n
    # 1 + 2α² + α⁴ = πα/n
    # α⁴ + 2α² - (π/n)α + 1 = 0
    
    # 数值求解
    alpha_guesses = [mpf('0.01'), mpf('0.05'), mpf('0.1'), mpf('0.5'), mpf('1.0')]
    solutions = []
    
    for alpha_0 in alpha_guesses:
        # Newton法
        alpha_i = alpha_0
        for _ in range(200):
            f = pi * alpha_i / (1 + alpha_i**2)**2 - n_val
            # f' = π·(1-3α²)/(1+α²)³
            fp = pi * (1 - 3*alpha_i**2) / (1 + alpha_i**2)**3
            if fabs(fp) < mpf('1e-30'):
                break
            alpha_new = alpha_i - f / fp
            if fabs(alpha_new - alpha_i) < mpf('1e-30'):
                break
            alpha_i = alpha_new
        
        if alpha_i > 0 and fabs(pi * alpha_i / (1 + alpha_i**2)**2 - n_val) < mpf('1e-20'):
            # 检查是否重复
            is_dup = False
            for s in solutions:
                if fabs(alpha_i - s) < mpf('1e-10'):
                    is_dup = True
                    break
            if not is_dup:
                solutions.append(alpha_i)
    
    return solutions

