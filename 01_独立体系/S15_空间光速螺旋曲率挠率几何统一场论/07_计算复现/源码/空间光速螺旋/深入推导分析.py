print(f"   ε₀ = e²/(4πcαℏ)")
print(f"   计算值: {eps0_from_formula:.15e}")
print(f"   CODATA: {eps0:.15e}")
print(f"   比值: {eps0_from_formula/eps0:.15f}")

# 这个公式是正确的！
# ε₀ = e²/(4πcαℏ) 是标准的精细结构常数定义
# α = e²/(4πcε₀ℏ)

