put(f"    α0 = tan(atan(α)/{k137}) = {nstr(alpha0_137,14)}")
put(f"    弱扭转近似 α0 ≈ α/{k137} = {nstr(ALPHA/k137,14)}")
put(f"    比值 α0/(α/{k137}) = {nstr(alpha0_137/(ALPHA/k137),15)}  (≈1, 验证弱扭转极限)")
# 反推: 若 α0 是某'更基础'耦合, 其倒数
put(f"    α0 的倒数 (基础耦合强度标度) = 1/α0 = {nstr(1/alpha0_137,4)}")
put(f"    = {k137} × (1/α) 的级联放大  →  '电子 α 是 137 级基础扭转的净投影'")
put(f"  [几何解读] 21号'137圈'直觉在此获得结构承载: 137 不是偶然, 而是级联阶数 k;")
