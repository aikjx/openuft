# =============================================================================
# 模型 1: 环形电荷分布
# =============================================================================
print("\n" + "=" * 90)
print("【模型 1】环形电荷分布 (厚度 δ)")
print("=" * 90)

print("""
  假设: 电子电荷均匀分布在半径 R, 厚度 δ 的环形带上
  
  电荷密度:
    σ = -e / (2πR · δ)  (面密度)
  
  螺旋运动:
    r(t) = (Rcos ωt, Rsin ωt, z)
  
  当电荷在 z 方向有扩展时，EDM 需要对 z 积分:
    d_z = (1/T) ∫ dt ∫ dz · ρ_charge(r,z) · z
    
  如果电荷分布在 z ∈ [bωT/2 - δ/2, bωT/2 + δ/2]:
    d_z = (-e/T) ∫ dt · bωT/2 · f(δ)
    
    其中 f(δ) 是电荷分布形状因子
""")

# 环形电荷的 EDM
delta_values = [mpf('0.01') * b_0, mpf('0.1') * b_0, mpf('0.5') * b_0, 
               mpf('1') * b_0, mpf('2') * b_0, mpf('5') * b_0]

print(f"\n  {'δ (m)':<20} {'δ/b':<15} {'d_z (C·m)':<25} {'d_z/d_line':<20} {'< 8.7×10⁻³⁴?':<20}")
print(f"  {'-'*100}")

d_line = pi * e_charge * b_0
for delta in delta_values:
    # 修正的 EDM: 电荷分布在厚度 δ 内
    # 假设均匀分布, 中心仍在 bωT/2
    # d_z = (-e/T) ∫ dt · bωT/2 = -πeb (与线电荷相同!)
    # 但如果分布中心偏离, 或形状不同...
    
    # 实际上, 均匀分布的环形电荷, EDM 仍为 πeb
    # 因为所有电荷元的 z 坐标中心仍在 bωT/2
    
    # 关键: 如果电荷分布关于中心对称, EDM 为零!
    # 如果电荷分布不对称, EDM = -πeb · (不对称因子)
    
    # 假设: 电荷集中在 z ∈ [0, bωT] (单侧分布)
    d_z_1side = -pi * e_charge * b_0  # 与线电荷相同
    
    # 假设: 电荷均匀分布在 z ∈ [-δ/2, δ/2] (对称分布)
    d_z_sym = mpf('0')  # 对称分布, EDM 为零!
    
    # 假设: 电荷分布在 z ∈ [0, δ] (非对称)
    # d_z = (-e/T) ∫ dt · ωt · [bωT/2 · (δ/bωT) + ...]
    # 这取决于分布的具体形式
    
    # 简化模型: EDM 被厚度压制
    suppression = b_0 / (b_0 + delta)  # 压制因子
    d_z_suppressed = d_line * suppression
    
    print(f"    {mp.nstr(delta, 15):<20} {mp.nstr(delta/b_0, 10):<15} {mp.nstr(d_z_suppressed, 15):<25} {mp.nstr(suppression, 10):<20} {'Yes' if abs(d_z_suppressed) < mpf('8.7e-34') else 'No':<20}")

# =============================================================================
# 模型 2: 环形电流的磁偶极矩
# =============================================================================
print("\n" + "=" * 90)
print("【模型 2】环形电流的磁偶极矩 (μ)")
print("=" * 90)

print("""
  环形电流: I = qω/(2π)
  
  磁偶极矩: μ = I · A = (qω/(2π)) · (πR²) = qωR²/2
  
  这是标准的磁偶极矩公式!
  
  对于电子:
    μ_e = eω_C_R_C²/2 = eh/(2m_e) (玻尔磁子!)
    
    自旋磁矩: μ_s = g·μ_B·S/ℏ = g·μ_B/2
    
    ZUFT 的磁矩: μ_ZUFT = qωR²/2 = μ_B (g=1)
    
    但实验 g ≈ 2.0023, 不是 1!
    这是 ZUFT 的另一个问题...
""")

mu_B = e_charge * hbar / (2 * m_e)
mu_ZUFT = e_charge * omega_C * R_C**2 / 2

print(f"  【玻尔磁子】")
print(f"    μ_B = eℏ/(2m_e) = {mp.nstr(mu_B, 15)} J/T")

print(f"\n  【ZUFT 磁矩】")
print(f"    μ_ZUFT = eωR_C²/2 = {mp.nstr(mu_ZUFT, 15)} J/T")
print(f"    μ_ZUFT/μ_B = {mp.nstr(mu_ZUFT/mu_B, 15)}")
print(f"    注意: ωR² = ω·(ℏ/(m_ec))² = ℏ²ω/(m_e²c²)")
print(f"    μ_ZUFT = e·ℏ²ω/(2m_e²c²) = e·ℏ/(2m_e)·(ℏω/(m_ec²))")
print(f"           = μ_B · (ℏω/(m_ec²)) = μ_B · (1) = μ_B")

print(f"\n  【问题】")
print(f"    ZUFT 给出 μ = μ_B, g = 1")
print(f"    实验: μ = g·μ_B/2, g ≈ 2.0023")
print(f"    ZUFT 缺了 g 因子的 2 倍!")

# =============================================================================
# 模型 3: 螺旋电流的磁偶极矩
# =============================================================================
print("\n" + "=" * 90)
print("【模型 3】螺旋电流的磁偶极矩")
print("=" * 90)

print("""
  螺旋电流: r(t) = (ρcos ωt, ρsin ωt, bωt)
  
  电流密度: J(r,t) = q·v(t)·δ³(r - r(t))
  
  磁偶极矩: μ = (1/2) ∫ d³r · r × J(r,t)
  
  对时间平均:
    μ_⊥ = (q/2T) ∫ dt · r_⊥ × v_⊥  (横向分量)
    μ_∥ = (q/2T) ∫ dt · r_∥ × v_∥  (纵向分量)
  
  横向分量 (环向):
    r_⊥ = (ρcos ωt, ρsin ωt, 0)
    v_⊥ = (-ρωsin ωt, ρωcos ωt, 0)
    r_⊥ × v_⊥ = (0, 0, ρ²ω)
    μ_⊥ = (q/2T) · ∫ dt · ρ²ω = qρ²ω/2
  
  纵向分量 (轴向):
    r_∥ = (0, 0, bωt)
    v_∥ = (0, 0, bω)
    r_∥ × v_∥ = 0  (平行矢量叉乘为零!)
    μ_∥ = 0
""")

mu_helical = e_charge * rho_0**2 * omega_C / 2
print(f"  【螺旋磁矩】")
print(f"    μ_helical = qρ²ω/2 = {mp.nstr(mu_helical, 15)} J/T")
