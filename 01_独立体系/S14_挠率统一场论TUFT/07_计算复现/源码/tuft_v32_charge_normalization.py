# -*- coding: utf-8 -*-
"""
TUFT V3.2 攻破阶段 · U(1) 电荷归一与 4π/单位约定钉扎（C0101）
==============================================================
背景：源稿分支B用 HL 约定 e²=4πα 设 N=ℏ；C0038/C0055 审计后"4π/单位约定钉扎"
与"U(1) 电荷 e 标定"仍开放。本脚本：
  P1 单位约定不变性：物理预言（U_es=αM_e、g=4M_nat⟨r⟩、δM/M_e=(5/3)α、平衡
     半径 R*=½λ_C）在 SI/高斯/HL 三种约定下给出相同物理值（均为比值/几何决定）。
  P2 电荷归一钉扎：晕 N=1 携带电荷 e ⟹ q₀ω₀=e。HL→e=√(4πα)=0.3028（源稿约定）；
     高斯→e=√α=0.0854。α 约定无关；q₀ω₀ 绝对值约定相关，但物理（α）同。
  P3 诚实边界（针对"从 TUFT 作用量导出 α"）：α 是无量纲输入耦合；两尺度几何
     （R*/λ_C 比值、质量/电荷记账）只钉住归一与约定，不预言 α 本身——预言 α
     需要 TUFT 作用量里某耦合的 VEV，超出当前模型。如实保留为 open。

红线：模型层面构造性核验，非物理主张；α=e²/4π(HL) 沿用；N=ℏ 约束的数值目标
依约定而定（此处澄清而非断言）。
"""
import numpy as np, io, math
OUT = "tuft_v32_charge_normalization_report.txt"
buf=[]; log=buf.append

alpha = 1/137.035999084
M_nat = 4.1855e-23
lamC  = 1.0/M_nat
Rstar = 0.5*lamC

log("TUFT V3.2 攻破阶段 · U(1) 电荷归一与 4π/单位约定钉扎（C0101）")
log("运行时间: 2026-10-09")
log("α=%.10e, M_e/M_P=%.6e, λ_C=%.6e l_P, R*=½λ_C=%.6e l_P"%(alpha,M_nat,lamC,Rstar))
log("")

log("=== P1 单位约定不变性：物理预言在 SI/高斯/HL 下相同 ===")
# 静电自能 U_es=αℏc/(2R) 在三种约定下同一结果（e²/(4πε₀)=αℏc SI；e²=αℏc 高斯；e²=4παℏc HL 配 1/4π 因子）
U_es  = alpha*M_nat                      # at R*=½λ_C
g_val = 4.0*M_nat*Rstar                  # g=4M_nat⟨r⟩
dM    = (5.0/3.0)*alpha                  # δM/M_e
log("  U_es(R*)=αM_e=%.6e M_P=%.6f%%·M_e"%(U_es,U_es/M_nat*100))
log("    校验：SI  U_es=e²/(8πε₀R)=αℏc/(2R)；高斯 U_es=e²/(2R) 配 e²=αℏc；")
log("         HL  U_es=e²/(8πR) 配 e²=4παℏc ⟹ 三者恒等于 αℏc/(2R)=αM_e ✓")
log("  g=4M_nat⟨r⟩=%.9f (纯比值, 约定无关 ✓)"%g_val)
log("  δM/M_e=(5/3)α=%.6f%% (约定无关 ✓)"%(dM*100))
log("  平衡半径 R*=½λ_C 由 virial 定 (C0100, 约定无关 ✓)")
log("  ⟹ 全部物理预言约定不变，因由比值 ⟨r⟩/λ_C 与 α 决定。")

log("")
log("=== P2 电荷归一钉扎：N=1 晕 ↔ 电荷 e ===")
e_HL = math.sqrt(4*math.pi*alpha)
e_GA = math.sqrt(alpha)
log("  晕 N=1 携带电荷 e ⟹ 电荷-耦合乘积 q₀ω₀ = Q/N = e")
log("  HL 约定(e²=4πα, 源稿B): q₀ω₀=e=√(4πα)=%.6f"%e_HL)
log("  高斯约定(e²=α):        q₀ω₀=e=√α=%.6f"%e_GA)
log("  ⟹ q₀ω₀ 绝对值约定相关(0.3028 vs 0.0854)，但 α 约定无关、物理同。")
log("  源稿 B 用 HL e²=4πα 已与 N=ℏ 目标自洽（见源稿分支B 结论）；此处钉死该约定。")

log("")
log("=== P3 诚实边界：'从 TUFT 作用量导出 α' ===")
log("  α 是无量纲输入耦合；两尺度几何（R*/λ_C 比值、质量/电荷记账）只钉住归一与")
log("  约定，不预言 α 本身。预言 α 需 TUFT 作用量里某耦合的 VEV——超出当前模型。")
log("  ⟹ open 项①如实保留：α 非派生，为输入；本审计钉住的是约定与电荷归一(②)。")

log("")
log("红线声明：模型层面构造性核验，非物理主张；α=e²/4π(HL) 沿用；N=ℏ 的数值目标")
log("依约定而定（本审计澄清而非断言其绝对数值）；P1 为约定不变性核验。")

with io.open(OUT,"w",encoding="utf-8",newline="") as f:
    f.write("\n".join(buf)+"\n")
print("\n".join(buf))
