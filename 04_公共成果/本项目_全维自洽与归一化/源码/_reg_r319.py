KEYS = [("│   ├── TUFT-r319_", "src"), ("├── 判定_TUFT-r319_", "jud"),
        ("- **r319（2026", "cmp"), ("### r319 ·", "det")]

ANCH_SRC = "│   ├── TUFT-r309_"
ANCH_JUD = "├── 判定_TUFT-r309_"
ANCH_CMP = "- **r309（2026"
ANCH_DET = "### r309 ·"


def main():
    if not os.path.exists(BAK):
        with io.open(README, encoding="utf-8") as f:
            bak_txt = f.read()
        os.makedirs(os.path.dirname(BAK), exist_ok=True)
        with io.open(BAK, "w", encoding="utf-8", newline="") as f:
            f.write(bak_txt)
        print("[r319] backup created:", os.path.basename(BAK))
    else:
        print("[r319] backup exists, keep it")

    with io.open(README, encoding="utf-8") as f:
        s = f.read()
    orig = s

    present = {k: (k in s) for k, _ in KEYS}
    if all(present.values()):
        print("SKIP 四处均已登记，幂等退出")
        for k, nm in KEYS:
            print("  %-4s %d" % (nm, s.count(k)))
        return 0

    lines = s.split("\n")
    added = 0

    if not present[KEYS[0][0]]:
        idx = [i for i, L in enumerate(lines) if L.startswith(ANCH_SRC)]
        assert len(idx) == 1, "锚点 src 命中 %d 次" % len(idx)
        lines.insert(idx[0] + 1, SRC_LINE)
        added += 1
    if not present[KEYS[1][0]]:
        idx = [i for i, L in enumerate(lines) if L.startswith(ANCH_JUD)]
        assert len(idx) == 1, "锚点 jud 命中 %d 次" % len(idx)
        lines.insert(idx[0] + 1, JUD_LINE)
        added += 1
    if not present[KEYS[2][0]]:
        idx = [i for i, L in enumerate(lines) if L.startswith(ANCH_CMP)]
        assert len(idx) == 1, "锚点 cmp 命中 %d 次" % len(idx)
        lines.insert(idx[0] + 1, COMPACT)
        added += 1

    s = "\n".join(lines)

    if not present[KEYS[3][0]]:
        had_nl = s.endswith("\n")
        s = s.rstrip("\n") + DETAIL
        if had_nl:
            s = s + "\n"
        added += 1

    with io.open(README, "w", encoding="utf-8") as f:
        f.write(s)

    with io.open(README, encoding="utf-8") as f:
        back = f.read()
    ok = True
    for k, nm in KEYS:
        c = back.count(k)
        print("  %-4s count=%d" % (nm, c))
        if c != 1:
            ok = False

    a = orig.split("\n")
    b = back.split("\n")
    dels = []
    for L in difflib.ndiff(a, b):
        if L.startswith("- "):
            dels.append(L[2:])
    print("[r319] diff 删除行数 = %d ; 新增行数 = %d ; added=%d" % (len(dels), len(b) - len(a), added))
    if dels:
        for d in dels[:5]:
            print("   ! DEL:", d[:110])
        ok = False
    last_orig = a[-1] if a else ""
    if last_orig and back.count(last_orig) != 1:
        print("   ! 原末行出现 %d 次（应 1）" % back.count(last_orig))
        ok = False
    for k, _ in KEYS:
        seg = [L for L in b if k in L]
        if len(seg) != 1:
            ok = False
    print("REG-OK" if ok else "REG-FAIL")
    return 0 if ok else 2


if __name__ == "__main__":
    sys.exit(main())
