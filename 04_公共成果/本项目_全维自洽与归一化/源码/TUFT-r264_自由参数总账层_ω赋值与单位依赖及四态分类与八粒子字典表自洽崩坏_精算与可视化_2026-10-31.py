def nhit(text, *toks):
    n = 0
    for t in toks:
        n += len(re.findall(re.escape(t), text))
    return n


def line_of(text, needle, nth=1):
    """返回第 nth 次出现 needle 的行号（1-based）与整行文本"""
    c = 0
    for i, ln in enumerate(text.splitlines(), 1):
        if needle in ln:
            c += 1
            if c == nth:
                return i, ln
    return None, ""


def sigdigits(s):
    """从 '2.5895361e-3' / '386.1489865' 这类字面量估计有效位数"""
    s = s.strip()
    m = re.match(r"^([-+]?)([0-9.]+)(?:[eE]([-+]?\d+))?$", s)
    if not m:
        return 1
    mant = m.group(2).replace(".", "").lstrip("0")
    return max(1, len(mant))


def pct(x):
    return "%s%%" % fmt(x * 100, 4)


