def omega_book_lp(kappa_fm, tau_fm, lp_num, unit_per_m):
    """书 L3369 的式子 ω = √(κ²+τ²)·c/ℓ_P，按指定长度单位记账。

    unit_per_m：1 m 等于多少个记账单位 U（fm ⇒ 1e15，cm ⇒ 1e2，m ⇒ 1）
    κ 以 U⁻¹ 计、c 以 U/s 计、ℓ_P 以 U 计。
    ★关键：ω_num = κ_num · (c_num/ℓ_P_num)，而 c_num/ℓ_P_num 与单位无关
      （U 约掉），故 **ω_num ∝ κ_num ∝ unit_per_m** —— 数值随单位线性摆动。
    """
    # κ 由 fm⁻¹ 换算到 U⁻¹：κ_num(U⁻¹) = κ_num(fm⁻¹) / (1 fm 含多少 U)
    fm_in_u = Decimal(str(unit_per_m)) / FM_PER_M        # 1 fm = ? U
    kappa_u = Decimal(str(kappa_fm)) / fm_in_u           # per U
    tau_u = Decimal(str(tau_fm)) / fm_in_u
    kmod = (kappa_u * kappa_u + tau_u * tau_u).sqrt()
    c_u = Decimal(str(C_LIGHT)) * Decimal(str(unit_per_m))   # U/s
    lp_u = D_LP_M * Decimal(str(unit_per_m))                 # U
    return kmod * c_u / lp_u, kmod, c_u / lp_u


def omega_unit_scan(kappa_fm, tau_fm):
    """对 fm / cm / m 三种记账单位算书式 ω，返回 (名称, unit_per_m, ω_num)"""
