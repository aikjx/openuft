import sympy as sp
from mpmath import mp, mpf, pi, sqrt, nstr, exp, log
mp.dps = 50

C    = mpf('299792458')
HBAR = mpf('1.05457181764615639e-34')
G    = mpf('6.67430e-11')
E    = mpf('1.602176634e-19')
ME   = mpf('9.1093837015e-31')
ALPHA_INV = mpf('137.035999084')
ALPHA = 1/ALPHA_INV
MEV2KG = mpf('1.78266192162789770e-30')

def rel(a, b):
    return abs(a - b) / abs(b)

def sec(t):
    print("\n" + "=" * 74)
    print("  " + t)
    print("=" * 74)

print("=" * 74)
