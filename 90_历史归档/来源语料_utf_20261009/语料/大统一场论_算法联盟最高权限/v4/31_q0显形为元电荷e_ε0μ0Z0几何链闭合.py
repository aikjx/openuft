if sys.platform == "win32":
    sys.stdout = io.TextIOWrapper(sys.stdout.buffer, encoding="utf-8", errors="replace")
from mpmath import mp, mpf, pi, sqrt, nstr
mp.dps = 50

C    = mpf('299792458')
HBAR = mpf('1.05457181764615639e-34')
E    = mpf('1.602176634e-19')
MU0  = mpf('1.25663706212e-6')
EPS0 = 1/(MU0*C*C)
G    = mpf('6.67430e-11')
ME   = mpf('9.1093837015e-31')
ALPHA_INV = mpf('137.035999084')
ALPHA = 1/ALPHA_INV
mP   = sqrt(HBAR*C/G)

L=[]
def sec(t):
    L.append("\n"+"="*70); L.append("  "+t); L.append("="*70)
def put(s=""):
    L.append(s)
def rel(a,b):
    return abs(a-b)/abs(b)

L.append("""
  ┌──────────────────────────────────────────────────────────────┐
  │  V4 融合版 · 31 号 · q0 显形为元电荷 e · ε0/μ0/Z0 几何链闭合 │
  │  算法联盟最高权限 · 全维求导/证明/验证/精算 · 2026-08-18      │
  └──────────────────────────────────────────────────────────────┘""")

# ============================================================
# [0] 29号 q0 显形
# ============================================================
sec("[0] 29号 q0 显形: q0 = e/e_geo (几何电流标尺, 无量纲比值)")
rho = HBAR/(ME*C); b = rho*ALPHA; R2 = rho**2+b**2
kappa = rho/R2; tau = b/R2
e_geo = 1/(4*pi*C*sqrt(kappa*tau))     # 29号几何式, 量纲 T
q0 = E / e_geo                          # 29号"电流本源尺度" = 无量纲比值标尺
put(f"  29号: e_geo=1/(4πc√(κτ))={nstr(e_geo,8)} [T]; q0=E/e_geo={nstr(q0,6)} (无量纲比值)")
put(f"  对照: 元电荷 e={nstr(E,8)} C; e_geo 量纲[T]; q0 把'几何时间单位'转换为'物理电流单位'")
put(f"  [显形] q0 = e/e_geo 是'元电荷在螺旋几何单位下的标尺比值' (无量纲 133.5)")
put(f"  因 e = q0·e_geo (定义), q0 不是新独立物理常数, 而是'几何→物理单位换算因子'")
put(f"  → 29号'待本源 q0' 显形为 '元电荷 e 与几何式 e_geo 的比值标尺' (已知测量锚)")
put(f"  [本质] q0 含 e 的测量值 → ε₀ 绝对值仍锚定 e; 几何给 κτ 结构, 绝对值锚 e (与 α 同族)")

# ============================================================
# [1] ε₀/μ₀/Z0 的 κτ 几何结构链
# ============================================================
sec("[1] ε₀/μ₀/Z0 的 κτ 几何结构链 — 全维求导证明")
# 标准定义链:
#   e² = 4π ε₀ ℏ c α        (A)  元电荷标准式
#   ε₀ = 1/(μ₀ c²)          (B)  真空常数关系
#   Z0 = μ₀ c = √(μ₀/ε₀)    (C)  真空阻抗
# 由 (A): ε₀ = e²/(4π ℏ c α)
# 由 29号几何: e = q0·e_geo (q0=E/e_geo 无量纲比值标尺) => 代入几何 e_geo:
#   ε₀ = (q0·e_geo)²/(4π ℏ c α) = q0²·e_geo²/(4π ℏ c α)
#   e_geo² = 1/(16π²c²κτ) => ε₀ = q0²/(64π³c³κτ ℏ α)  (29号式, 用 q0 比值标尺)
eps0_geo = q0**2/(64*pi**3*C**3*kappa*tau*HBAR*ALPHA)
put(f"  1a ε₀ 几何式 (29号 q0² 代入): ε₀=q0²/(64π³c³κτℏα)")
put(f"     = {nstr(eps0_geo,12)} F/m  vs 实测 {nstr(EPS0,12)}")
put(f"     相对误差 = {nstr(rel(eps0_geo,EPS0),3)}  -> {'PASS(机器零)' if rel(eps0_geo,EPS0)<mpf('1e-9') else 'FAIL'}")
# 1b μ0 几何: μ0=1/(eps0 c^2) => μ0 = 64π³c κτ ℏ α / q0²
mu0_geo = 1/(eps0_geo*C**2)
put(f"  1b μ₀ 几何式: μ0=1/(ε₀c²)=64π³cκτℏα/q0²")
put(f"     = {nstr(mu0_geo,10)} vs 实测 μ0={nstr(MU0,10)}")
put(f"     相对误差 = {nstr(rel(mu0_geo,MU0),3)}  -> {'PASS(机器零)' if rel(mu0_geo,MU0)<mpf('1e-9') else 'FAIL'}")
# 1c Z0 几何: Z0=μ0 c
Z0_geo = mu0_geo*C
put(f"  1c Z0 几何式: Z0=μ0 c")
put(f"     = {nstr(Z0_geo,6)} Ω vs 实测 Z0={nstr(MU0*C,6)}")
put(f"     相对误差 = {nstr(rel(Z0_geo,MU0*C),3)}  -> {'PASS(机器零)' if rel(Z0_geo,MU0*C)<mpf('1e-9') else 'FAIL'}")
# 1d Z0 的纯 α 表达 (无 κτ, 因 Z0 是比值): Z0=4πℏα/e²
Z0_alpha = 4*pi*HBAR*ALPHA/(E**2)
put(f"  1d Z0 纯 α 表达: Z0=4πℏα/e²={nstr(Z0_alpha,6)} Ω (结构闭合, 数值需 e 锚)")
put(f"     → Z0 只依赖 α 与 e, 不依赖 κτ (因 Z0 是阻抗比值, κτ 在 μ0/eps0 中相消)")
put(f"     [注] q0²=17830 是 e 与 e_geo 的比值平方 (单位换算因子), 非 e 本身数值")

# ============================================================
# [2] 符号求导: ε₀/μ₀ 对 κτ 的依赖
# ============================================================
sec("[2] 符号求导 — ε₀/μ₀ 对 κτ 的几何依赖")
