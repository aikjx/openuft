def insert_after(text, anchor, payload):
    """在首个以 anchor 开头的行之后插入 payload（单行文本）。"""
    lines = text.split("\n")
    for i, ln in enumerate(lines):
        if ln.startswith(anchor):
            lines.insert(i + 1, payload)
            return "\n".join(lines), i + 2
    return None, -1


