def md_table(header, rows):
    out = ['| ' + ' | '.join(header) + ' |',
           '|' + '|'.join(['---'] * len(header)) + '|']
    for r in rows:
        out.append('| ' + ' | '.join(str(c).replace('|', '\\|') for c in r) + ' |')
    return '\n'.join(out)


def write_csv(path, header, rows):
    with open(path, 'w', encoding='utf-8-sig', newline='') as f:
        w = csv.writer(f)
        w.writerow(header)
        w.writerows(rows)


def main():
    write_csv(ROOT / '场元数据表.csv', META_HEADER, META)
    (ROOT / '06_场元数据表.md').write_text(
        META_DOC.replace('{table}', md_table(META_HEADER, META)),
        encoding='utf-8')

    write_csv(ROOT / '现象覆盖矩阵.csv', PHEN_HEADER, PHEN)
    ok_status = ('已确立', '已验证')
    n_ok = sum(1 for r in PHEN if any(r[5].startswith(s) for s in ok_status))
    n_part = sum(1 for r in PHEN if '部分' in r[5] or '定性' in r[5])
    n_untest = sum(1 for r in PHEN if '未检验' in r[5])
    n_fail = len(PHEN) - n_ok - n_part - n_untest
    tot = len(PHEN)
    (ROOT / '07_现象覆盖矩阵.md').write_text(
        PHEN_DOC.replace('{table}', md_table(PHEN_HEADER, PHEN))
        .replace('{n_ok}', str(n_ok)).replace('{p_ok}', str(100.0 * n_ok / tot))
        .replace('{n_part}', str(n_part)).replace('{p_part}', str(100.0 * n_part / tot))
        .replace('{n_untest}', str(n_untest)).replace('{p_untest}', str(100.0 * n_untest / tot))
        .replace('{n_fail}', str(n_fail)).replace('{p_fail}', str(100.0 * n_fail / tot)),
        encoding='utf-8')
    print('已生成：场元数据表（{} 行）、现象覆盖矩阵（{} 行）'.format(len(META), len(PHEN)))


if __name__ == '__main__':
    main()
