# 外输标记词：只认「同一行内、与符号距离 ≤40 字符」的近距离共现，
# 避免把全书 162 次「外输」泛化到每个符号。
FIT_TOKENS = ("外输", "外部输入", "实验输入", "观测为输入", "实验值",
              "CODATA", "PDG")

NUM_LIT_RE = re.compile(r"[-+]?\d+(?:\.\d+)?(?:\s*[×x*]\s*10\^?[−\-]?\d+|\s*[eE][-+]?\d+)?")


def sym_pat(sym):
    """单字母 ASCII 符号加字母边界，避免 'b' 命中 'sub'、'm' 命中 'MeV'。"""
    e = re.escape(sym)
    if re.match(r"^[A-Za-z]$", sym):
        return r"(?<![A-Za-z])" + e + r"(?![A-Za-z])"
    return e


def symbol_census(text):
    """三路符号发现：Unicode / LaTeX 宏 / 下标形式。"""
    out = {}
    # 路 1：Unicode 直接计数
    for sym, _, _ in CORE_SYMBOLS:
        out.setdefault(sym, {"unicode": 0, "latex": 0, "sub": 0})
        out[sym]["unicode"] = text.count(sym)
    # 路 2：LaTeX 宏 \omega 等
    latex_map = {"ω": r"\omega", "κ": r"\kappa", "τ": r"\tau", "ρ": r"\rho",
                 "α": r"\alpha", "λ": r"\lambda", "μ": r"\mu",
                 "ℓ_P": r"\ell_P", "m_P": r"m_P", "R_c": r"R_c"}
    for sym, mac in latex_map.items():
        out.setdefault(sym, {"unicode": 0, "latex": 0, "sub": 0})
        out[sym]["latex"] = len(re.findall(re.escape(mac) + r"(?![a-zA-Z])", text))
    # 路 3：下标 / 上标形式 ℓ_P、m_P、R_c 等的 Unicode 变体
    sub_map = {"ℓ_P": ("ℓ_P", "ℓP", "l_P"), "m_P": ("m_P", "mP"),
               "R_c": ("R_c", "Rc", "R_c^A")}
    for sym, variants in sub_map.items():
        out.setdefault(sym, {"unicode": 0, "latex": 0, "sub": 0})
        out[sym]["sub"] = sum(text.count(v) for v in variants)
    return out


def classify_symbol(sym, mac, text):
    """机器四态分类（定义见下，全部由正则机读决定，不手填）。

    NEVER = 全书既没给过数值，也没给过定义式
    DEF   = 只给过定义式（SYM = 表达式），没有可取的数值
    FIT   = 有数值，且同一行近距离被书标注为外输/实验输入
    NUM   = 有数值，且书未标注其来源
    """
    pat = "(?:%s|%s)" % (sym_pat(sym), re.escape(mac) + r"(?![a-zA-Z])")
    lines = text.splitlines()
    total = len(re.findall(pat, text))

    # ① 赋值：SYM = 右端；右端含数字记 NUM 型，含符号式记 DEF 型
    assigns_num, assigns_sym, samples = [], [], []
    for mt in re.finditer(pat + r"\s*(?:=|＝|≈)\s*([^\n|，,。;；]{1,48})", text):
        rhs = mt.group(1).strip()
        if NUM_LIT_RE.match(rhs):
            assigns_num.append(rhs)
            if len(samples) < 6:
                samples.append(rhs)
        else:
            assigns_sym.append(rhs)

    # ② 数值列表头：符号出现在表头行（下一行为 |--- 分隔）⇒ 该列有数值
    header_value = False
    hdr_samples = []
    for i, ln in enumerate(lines):
        s = ln.strip()
        if not s.startswith("|") or "---" in s:
            continue
        nxt = lines[i + 1].strip() if i + 1 < len(lines) else ""
        if not (nxt.startswith("|") and "---" in nxt):
            continue
        if re.search(pat, s):
            header_value = True
            if len(hdr_samples) < 4:
                hdr_samples.append(s[:70])

    # ③ 标签-数值表：同一行内某格含符号、另一格是数字（如 | 角频率 ω | 7.763×10²⁰ s⁻¹ |）
    label_value = False
    lab_samples = []
    for ln in lines:
        s = ln.strip()
        if not s.startswith("|") or "---" in s:
            continue
        cells = [c.strip() for c in s.strip("|").split("|")]
        idx = [j for j, c in enumerate(cells) if re.search(pat, c)]
        if not idx:
            continue
        hit = False
        for j in idx:
            for k, c in enumerate(cells):
                if k == j:
                    continue
                if NUM_LIT_RE.match(c.replace("$", "").strip()):
                    hit = True
                    if len(lab_samples) < 4:
                        lab_samples.append(c[:40])
                    break
            if hit:
                break
        if hit:
            label_value = True

    has_value = bool(assigns_num) or header_value or label_value

    # ④ 外输归属（决定性判据）：机器抽取书**自己**的「外输清单」段落，
    #   看该符号是否被列入。★不用「关键词同行共现」那种宽口径——全书「外输」162 次，
    #   宽口径会把每个符号都判成外输，分类器失去分辨力。
    list_hit, list_evidence = False, ""
    for mt in re.finditer(r"外输清单", text):
        seg = text[mt.start(): mt.start() + 220]
        if re.search(pat, seg):
            list_hit = True
            list_evidence = seg[:110]
            break

    # ④b 参考量（只登记不判决）：作用域共现行数——表格行取整行，非表格行按「；。」切子句。
    toks = "|".join(FIT_TOKENS)
    fit_lines, fit_samples = 0, []
    for ln in lines:
        s = ln.strip()
        if not re.search(pat, s):
            continue
        scopes = [s] if s.startswith("|") else re.split(r"[；;。]", s)
        for sc in scopes:
            if re.search(pat, sc) and re.search(toks, sc):
                fit_lines += 1
                if len(fit_samples) < 3:
                    fit_samples.append(sc[:70])
                break

    definitional = len(assigns_sym) > 0
    if not has_value and not definitional:
        state = STATE_NEVER
    elif list_hit:
        state = STATE_FIT
    elif not has_value and definitional:
        state = STATE_DEF
    else:
        state = STATE_NUM

    return {"state": state, "total": total, "num_assign": len(assigns_num),
            "sym_assign": len(assigns_sym),
            "table_num": (1 if header_value else 0) + (1 if label_value else 0),
            "samples": (samples + lab_samples)[:4],
            "fit_lines": fit_lines, "fit_samples": fit_samples,
            "list_hit": list_hit, "list_evidence": list_evidence,
            "has_value": bool(has_value), "definitional": definitional}


