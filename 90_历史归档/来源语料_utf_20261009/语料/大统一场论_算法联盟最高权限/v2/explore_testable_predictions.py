# 螺旋的 Berry 相位: 粒子沿闭合路径运动时的几何相位
# 对螺旋参数化: x(t) = (Rcos(t), Rsin(t), bt)
# Berry 相位 = 2π·(1 - cosθ) 其中 cosθ = κ/√(κ²+τ²)

cos_theta = kappa / sqrt(kappa**2 + tau**2)
sin_theta = tau / sqrt(kappa**2 + tau**2)
berry_phase = 2 * pi * (1 - cos_theta)
print(f"\n  Berry = {mp.nstr(berry_phase, 12)} rad")

print(f"\n  螺旋 Berry 相位:")
print(f"    cosθ = κ/√(κ²+τ²) = {mp.nstr(cos_theta, 12)}")
print(f"    sinθ = τ/√(κ²+τ²) = {mp.nstr(sin_theta, 12)}")
print(f"    Berry = 2π(1-cosθ) = {mp.nstr(berry_phase, 12)} rad")
print(f"    Berry ≈ α (因 α = τ/κ ≈ sinθ/cosθ ≈ θ 小时 θ ≈ α)")

# 这是否与电子 g-2 有关?
# g-2 = 2(1 + δ), 若 δ = Berry/(2π)?
