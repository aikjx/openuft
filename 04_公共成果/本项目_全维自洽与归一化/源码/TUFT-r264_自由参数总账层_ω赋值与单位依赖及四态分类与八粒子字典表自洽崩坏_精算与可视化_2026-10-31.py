def repair_pricing():
    out = {"EMPTY": 0, "SUICIDE": 0, "SURVIVE": 0, "total": 0}
    n = len(REPAIR_KEYS)
    for mask in range(1 << n):
        have = {REPAIR_KEYS[i] for i in range(n) if (mask >> i) & 1}
        out["total"] += 1
        if len(have) < n:
            out["EMPTY"] += 1
        elif SUICIDE_PAIR.issubset(have):
            out["SUICIDE"] += 1
        else:
            out["SURVIVE"] += 1
    return out


