def load_ids(fn):
    path = os.path.join(DATA_DIR, fn)
    if not os.path.exists(path):
        return None
    with io.open(path, encoding="utf-8") as fh:
        d = json.load(fh)
    ids = set()
    for k in ("items", "records", "条目", "RESULTS"):
        for it in (d.get(k) or []):
            if isinstance(it, dict):
                v = it.get("id") or it.get("name")
                if v:
                    ids.add(str(v))
    return ids


