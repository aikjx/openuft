# ============================================================
sec("[3] 连分数展开: α 的最优几何有理数近似")
# α_inv = 137.035999084 的连分数
def continued_fraction(x, max_terms=12):
    terms=[]
    for _ in range(max_terms):
        a=int(floor(x))
        terms.append(a)
        if abs(x-a)<mpf('1e-30'):
            break
        x=1/(x-a)
    return terms
cf = continued_fraction(ALPHA_INV)
put(f"  α_inv = {nstr(ALPHA_INV,12)} 的连分数 = [{cf[0]}; {', '.join(str(t) for t in cf[1:])}]")
# 逐次收敛子
def convergents(cf):
    convs=[]
    for i in range(1,len(cf)+1):
        # 计算第 i 个收敛子 p/q
        p0,q0=mpf(1),mpf(0)
        p1,q1=mpf(cf[0]),mpf(1)
        for a in cf[1:i]:
            p0,p1=p1,p0+a*p1
            q0,q1=q1,q0+a*q1
        convs.append((p1,q1))
    return convs
cv = convergents(cf)
put(f"  收敛子 (α^{-1} 候选值):")
for (p,q) in cv[:8]:
    a_inv=p/q
    r=rel(a_inv, ALPHA_INV)
    put(f"    [{p}/{q}] = 1/α ≈ {nstr(a_inv,10)}  残差={nstr(r,4)}")
put(f"  [洞察] 第一个收敛子 137/1 = 1/α 给出'α≈1/137'的整数级解释;")
put(f"    更高阶收敛子 (如含 137; 13,...) 把 0.036 的小数修正也几何化")
put(f"  [诚实] 连分数只说明'α 是简单有理数附近的可解释数', 不挑唯一值")

