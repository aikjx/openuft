def kk(k):
    return k.replace("@SLUG@", SLUG)


def read(p):
    with io.open(p, "r", encoding="utf-8", newline="") as f:
        return f.read()


def write(p, s):
    with io.open(p, "w", encoding="utf-8", newline="") as f:
        f.write(s)


def present(txt):
    return {name: (kk(k) in txt) for k, name in KEYS}


def apply_once(txt):
    """返回 (new_txt, log)。所有插入都按「已存在则跳过」。"""
