class Dim(object):
    __slots__ = ("e",)

    def __init__(self, M=0, L=0, T=0):
        self.e = (M, L, T)

    def __add__(self, o):
        return Dim(*self.e) if self.e == o.e else Dim(*[a + b for a, b in zip(self.e, o.e)])

    def __sub__(self, o):
        return Dim(*self.e) if self.e == o.e else Dim(*[a - b for a, b in zip(self.e, o.e)])

    def __mul__(self, o):
        return Dim(*[a + b for a, b in zip(self.e, o.e)])

    def __truediv__(self, o):
        return Dim(*[a - b for a, b in zip(self.e, o.e)])

    def __pow__(self, k):
        return Dim(*[a * k for a, b in zip(self.e, (k, k, k))])

    def __eq__(self, o):
        return isinstance(o, Dim) and self.e == o.e

    def __ne__(self, o):
        return not self.__eq__(o)

    def __hash__(self):
        return hash(self.e)

    def __repr__(self):
        parts = []
        for n, v in zip(("M", "L", "T"), self.e):
            if v != 0:
                parts.append(n if v == 1 else "%s^%g" % (n, v))
        return "*".join(parts) if parts else "1(dimensionless)"


