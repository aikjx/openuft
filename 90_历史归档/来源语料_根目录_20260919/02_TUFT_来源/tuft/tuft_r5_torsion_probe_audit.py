import os
import sys
import math

try:
    sys.stdout.reconfigure(encoding="utf-8", errors="replace")
except Exception:
    pass

HERE = os.path.dirname(os.path.abspath(__file__))
REPORT = os.path.join(HERE, "tuft_r5_report.txt")

# ---------------------------------------------------------------- 常数（CODATA 2022）
C = 2.99792458e8
G = 6.67430e-11
HBAR = 1.054571817e-34
MUB = 9.2740100783e-24          # 玻尔磁子 J/T
NA = 6.02214076e23
M_FE = 55.845e-3                # kg/mol
RHO_FE = 7874.0                 # kg/m^3

OUT = []


def sec(t):
    OUT.append("\n" + "=" * 78)
    OUT.append("  " + t)
    OUT.append("=" * 78)


def put(s=""):
    OUT.append(s)


def rec(name, ok, detail):
    OUT.append("  %s %s  |  %s" % ("[PASS]" if ok else "[FAIL]", name, detail))
    return ok


def bnd(name, detail):
    OUT.append("  [BOUNDARY] %s  |  %s" % (name, detail))


def info(name, detail):
    OUT.append("  [INFO] %s  |  %s" % (name, detail))


def main():
    sec("TUFT-R5 地面挠率探测实验设计 · 严格审计")
    put("  对象：用户草稿（传感原理 / 装置架构 / 噪声预算 / GR 区分判据）")
    put("  方法：LaTeX 复原 + 独立精算 + 量纲审计 + EC 自然耦合量级检验")

    # ======================= 0. LaTeX 损坏复原 =======================
    sec("0. LaTeX 损坏复原（\\\\(^X\\\\) → X）")
    info("0", "草稿转义残留形如 \\(^1\\)、\\(^{87}\\)，语义为数字/上标本身；这是渲染转义事故，非物理内容")
    for a, b in [("\\(^1\\)0^-1 2 torr", "10^-12 torr"),
                 ("$^{87}$Rb", "$^{87}$Rb（铷-87）"),
                 ("10^6 原子", "10^6 原子"),
                 ("S_tot ~ 10^21 ħ", "S_tot ~ 10^21 ħ"),
                 ("δT ~ 10^-5 s^-1", "δT ~ 10^-5 s^-1"),
                 ("θ ~ 10^-9 rad", "θ ~ 10^-9 rad")]:
        put("    复原：%s" % b)
    info("0", "复原不改变任何物理主张，仅恢复可读性；下文数值均按复原后的字面值审计")

    # ======================= 1. 方案A 原子干涉 =======================
    sec("1. 方案A 冷原子自旋干涉仪 · 精算")
    N_atom = 1e6
    dphi_shot = 1.0 / math.sqrt(N_atom)
    rec("A: 单次散粒噪声 δφ=1/√N",
        abs(dphi_shot - 1e-3) / 1e-3 < 1e-6,
        "N=1e6 ⇒ δφ=%.4e rad（原文 1e-3）" % dphi_shot)
    T_int = 1.0
    dT_shot = dphi_shot / T_int
    rec("A: 单次挠率灵敏度 δT=δφ/T_int",
        abs(dT_shot - 1e-3) / 1e-3 < 1e-6,
        "δT=%.4e s^-1（原文 1e-3）" % dT_shot)
    N_avg = 1e4
    dT_avg = dT_shot / math.sqrt(N_avg)
    rec("A: 1e4 次平均 → 灵敏度",
        abs(dT_avg - 1e-5) / 1e-5 < 1e-6,
        "δT=%.4e s^-1（原文 1e-5）" % dT_avg)
    T_source = 1e-4
    dphi_signal = T_source * T_int
    rec("A: 信号相位 Δφ=T_source·T_int",
        abs(dphi_signal - 1e-4) / 1e-4 < 1e-6,
        "Δφ=%.4e（原文 1e-4；量纲=相位，无量纲 ✓）" % dphi_signal)
    SNR_A = dphi_signal / dT_avg
    rec("A: 信噪比 SNR=Δφ/δT",
        abs(SNR_A - 10) / 10 < 1e-6,
        "SNR=%.1f（原文 10）——**算术自洽**" % SNR_A)
    bnd("A: 前提 T_source=1e-4 s^-1",
        "该值来自前章『厘米级挠率谐振腔』，本审计无法从第一性验证（见 §4 量级检验）")
    bnd("A: 相位公式 φ=(1/ħ)∫(S↑−S↓)·T dt",
        "要求 (S↑−S↓)=ħ 且 T 单位=s^-1（把挠率当频率），需 TUFT 显式约定；标准微分几何挠率量纲为 1/长度")

    # ======================= 2. 方案B 扭秤 =======================
    sec("2. 方案B 自旋共振扭秤 · 精算（含 S_tot 独立重算）")
    m_fe = 1e-2
    N_fe = m_fe / M_FE * NA
    mu_atom = 2.22 * MUB                       # Fe 饱和磁矩/原子
    P = 0.1
    S_atom_hbar = P * mu_atom / (2 * MUB)          # 每原子自旋（单位 ħ；g=2：S/ħ=μ/(2μ_B)）
    S_tot_hbar = N_fe * S_atom_hbar                # 总自旋（单位 ħ）
    S_tot_SI = S_tot_hbar * HBAR
    rec("B: 10g Fe 原子数",
        abs(N_fe - 1.078e23) / 1.078e23 < 0.01,
        "N=%.3e（M=55.845 g/mol, N_A）" % N_fe)
    info("B", "饱和磁矩 2.22 μ_B/原子；极化率 P=%.1f ⇒ 每原子自旋 %.4f ħ" % (P, S_atom_hbar))
    info("B", "独立重算 S_tot = %.3e ħ（原文 1e21 ħ）" % S_tot_hbar)
    ratioS = S_tot_hbar / 1e21
    rec("B: S_tot 与原文一致?",
        abs(math.log10(ratioS)) < 0.3,
        "偏差 %.1f 倍（原文偏低）；若 P=0.01 则 ≈1e21 与原文吻合 ⇒ 原文『P=0.1』与『1e21』不自洽"
        % ratioS)
    tau = S_tot_SI * T_source
    info("B", "力矩 τ=S_tot·T = %.4e N·m（原文 ~1e-17；用原文 S_tot=1e21 ħ 则 %.3e N·m）"
         % (tau, 1e21 * HBAR * T_source))
    kappa_tors = 1e-8
    theta = 1e21 * HBAR * T_source / kappa_tors    # 按原文 S_tot 复算，隔离 S_tot 问题
    rec("B: 偏转角 θ=τ/κ_torsion（按原文 S_tot）",
        abs(theta - 1e-9) / 1e-9 < 0.1,
        "θ=%.3e rad（原文 1e-9）" % theta)
    noise_theta = 1e-12
    SNR_B = theta / noise_theta
    rec("B: SNR=θ/噪声",
        abs(SNR_B - 1e3) / 1e3 < 0.1,
        "SNR=%.0f（原文 1000）" % SNR_B)
    bnd("B: 噪声口径", "θ(振幅, rad) 直接比 1e-12 rad/√Hz ——量纲不一致（缺 √带宽）；窄带共振下近似可用，需显式化为谱密度比较")
    bnd("B: 光学杠杆 1e-12 rad/√Hz", "为极高指标（接近 Eöt-Wash 级），需超导/极端隔振，原文未给实现路径")

    # ======================= 3. 方案C NMR =======================
    sec("3. 方案C NMR 挠率谱仪 · 精算")
    domega = T_source          # 原文 (κ/2ħ)T·S，取 κ=1, S=ħ ⇒ Δω≈T/2~5e-5；原文取 1e-4（同量级）
    rec("C: 进动频移 Δω 量级",
        abs(domega - 1e-4) / 1e-4 < 1.0,
        "Δω≈T_source=%.1e rad/s（原文 1e-4；O(1) 因子差异）" % domega)
    res_nmr = 1e-6
    SNR_C = domega / res_nmr
    rec("C: SNR=Δω/分辨率",
        abs(SNR_C - 100) / 100 < 1e-6,
        "SNR=%.0f（原文 100）" % SNR_C)
    bnd("C: NMR 分辨率 1e-6 Hz", "亚微赫兹（~1 μHz）需超长平均 + 超稳磁体；属乐观但非不可能")
    bnd("C: 公式 ω=γB+(κ/2ħ)T", "遗漏自旋因子 S；补 S~ħ 后方量级自洽（Δω≈κT/2）")

    # ======================= 4. 量纲审计（自旋-挠率耦合） =======================
    sec("4. 求导证明：自旋-挠率耦合项量纲审计")
    put("  草稿：L = -(κ/2) S^μ T_μ；  Δω = (κ/2ħ) T·S")
    put("  设 [S]=J·s, [T]=s^-1（草稿取挠率为频率）, [κ]=无量纲：")
    put("     [S·T] = J·s · s^-1 = J = 能量 ✓（可与 mc² 相加）")
    put("     [Δω] = (1/[ħ])·J = (1/(J·s))·J = s^-1 = 频率 ✓")
    rec("4: S·T 作能量、Δω 作频率 自洽", True,
        "在『T 取频率单位 + κ 无量纲』约定下自洽 —— 但该约定需显式声明")
    bnd("4: 挠率量纲约定", "标准微分几何挠率 T^λ_μν 量纲 = 1/长度；草稿用 s^-1（= 空间挠率×c）。二者仅在 TUFT 显式约定下等价")
    bnd("4: 耦合常数 κ 的地位", "草稿把 κ 当自由参数；若 TUFT 继承爱因斯坦-嘉当结构，κ 被 G 固定（见 §5），不可自由选取 O(1)")

    # ======================= 5. EC 自然耦合量级检验（核心） =======================
    sec("5. 爱因斯坦-嘉当自然耦合下的挠率量级（可行性核心检验）")
    n_fe = RHO_FE / M_FE * NA
    info("5", "Fe 自旋密度：n=%.3e /m^3，s≈1.1ħ·n=%.3e kg/(m·s)" % (n_fe, n_fe * 1.1 * HBAR))
    s_spin = n_fe * 1.1 * HBAR
    T_EC = (G / C ** 3) * s_spin          # 1/m（挠率=1/长度）
    T_EC_freq = C * T_EC                   # s^-1（换算为频率单位以与草稿比较）
    info("5", "EC 约定 T=(G/c³)·s ⇒ T=%.3e m^-1；换算频率 T·c=%.3e s^-1" % (T_EC, T_EC_freq))
    gap = T_source / T_EC_freq
    rec("5: 草稿 T_source=1e-4 s^-1 是否可达?",
        gap < 1e6,
        "相差 %.2e 倍（≈10^%.1f）——EC 自然耦合给出的实验室挠率约 1e-33 s^-1" % (gap, math.log10(gap)))
    s_needed = T_source / (C * G / C ** 3)    # 需要的自旋密度
    n_needed = s_needed / (1.1 * HBAR)
    info("5", "若要 T=1e-4 s^-1，需自旋密度 s=%.3e kg/(m·s)，即 n=%.3e 原子/m^3" % (s_needed, n_needed))
    info("5", "对比：核物质密度 ~1e44 核子/m^3 —— 仍差 ~10^%.0f 倍" % (math.log10(n_needed) - 44))
    put("")
    put("  ⇒ 核心结论：草稿的可行性完全依赖『人工挠率谐振腔』将挠率放大 ~10^29 倍。")
    put("     在标准 EC 耦合（κ∝G）下，地面实验挠率 ~1e-33 s^-1，SNR 由 10 → ~1e-29，不可探测。")
    put("     故该实验设计的可行性，等价于『挠率谐振腔可产生 T~1e-4 s^-1』这一【未证】前提。")

    # ======================= 6. 噪声预算表口径 =======================
    sec("6. 噪声预算表（§5）口径审计")
    bnd("6: 单位混用", "表中『总噪声(积分1h)』列出现 rad 与 rad/s 混排；挠率灵敏度列 s^-1，需与信号相位(rad)/频率(rad·s^-1)统一")
    bnd("6: 积分定律", "各行噪声为 rad/√Hz，积分 1h 应 ×√3600=60；表中未见显式 √ 关系，建议补列")
    info("6", "扭秤行『量子投影噪声 —』：扭秤无原子投影噪声，留空合理；NMR 行缺热噪声，建议补")

    # ======================= 7. GR 区分判据 =======================
    sec("7. GR/电磁区分判据（§6）审计")
    for i, (k, v) in enumerate([
        ("自旋相关性", "反转自旋→信号反号；非极化→信号消失。**有效**（EC 中自旋确实耦合挠率，GR 中否）"),
        ("手性不对称", "T_L≠T_R。EC 中：若挠率由自旋张量源，则其轴矢部分手性；**有效但需显式建模型**"),
        ("电荷无关性", "挠率力与电荷无关。**有效**（与电磁对比）"),
        ("频率响应", "信号严格跟随源调制。**有效**（锁相/共模抑制标准手段）"),
        ("空间分布", "T(r)∝e^{-r/λ_T}。**需前置建立 λ_T 的场方程**；TUFT 未给挠率动力学（前章亦为开放）"),
    ], 1):
        bnd("判据%d %s" % (i, k), v)
    put("")
    put("  ⇒ 判据 1–4 是稳健的实验证伪工具（可排除电磁/机械假象）；判据 5 依赖尚未建立的挠率场方程。")
    put("     关键盲点：五条判据都无法区分『TUFT 挠率』与『其他任何自旋-力矩耦合的新物理』——")
    put("     它们证伪电磁/GR，但不唯一认证 TUFT。加一条『耦合常数与 G 的关系检验』才闭合。")

    # ======================= 8. 综合判定 =======================
    sec("8. 综合判定（诚实分级）")
    put("  [算术层]  PASS —— 各比值/量级内部自洽（SNR 10 / 1000 / 100 均可复现）。")
    put("  [数值层]  FAIL×1 —— S_tot=1e21 ħ 与『P=0.1, 10g Fe』不自洽（应 ~1.2e22 ħ，偏 ~12 倍）。")
    put("  [量纲层]  BOUNDARY —— S·T/Δω 在『T 作频率+κ 无量纲』约定下自洽，但该约定与标准挠率(1/长度)不同，需显式声明。")
    put("  [可行性]  FAIL（关键）—— EC 自然耦合下实验室挠率 ~1e-33 s^-1，与草稿 1e-4 相差 ~1e29；")
    put("            可行性完全由未证的『挠率谐振腔』承担。")
    put("  [判据层]  BOUNDARY —— 4 条稳健、1 条依赖未建场方程；且不足以唯一认证 TUFT。")
    put("")
    put("  总评：实验**方法论**（锁相/差分/多方案交叉）专业且可复现；")
    put("        但**物理可行性**未被建立——瓶颈不在探测器灵敏度，而在『挠率如何被产生到 1e-4 s^-1』。")
    put("        建议：把本章降级为『探测方案预研』，前置条件是先给出挠率产生机制的定量第一性推导 + 耦合常数 κ 的地位。")
    put("")
    put("红线声明：本审计只做量纲/数值核对与方法学评估；不主张 TUFT 成立或证伪。")

    txt = "\n".join(OUT) + "\n"
    print(txt)
    try:
        with open(REPORT, "w", encoding="utf-8") as fh:
            fh.write(txt)
        print("[报告已写入] " + REPORT)
    except Exception as exc:
        print("[warn] " + str(exc))


if __name__ == "__main__":
    main()
