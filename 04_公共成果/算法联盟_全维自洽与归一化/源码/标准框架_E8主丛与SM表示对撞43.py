# ============ 第 1 节：E8 及子群链维数恒等式（精确整数） ============
checks = []
def chk(name, ok, detail):
    checks.append((name, bool(ok), detail))

# E8 基本量
chk("E8 维数", 248 == 248, "dim E8 = 248（秩 8，自对偶）")

# E8 ⊃ E7×SU(2)：248 = (133,1)+(56,2)+(1,3)
v = 133*1 + 56*2 + 1*3
chk("E8⊃E7×SU(2) 分支", v == 248, "248 = 133(adj E7) + 2×56(E7 基本) + 3(adj SU2)")

# E8 ⊃ E6×SU(3)：248 = (78,1)+(27,3)+(27̄,3̄)+(1,8)
v = 78*1 + 27*3 + 27*3 + 1*8
chk("E8⊃E6×SU(3) 分支", v == 248, "248 = 78(adj E6) + 3×27 + 3×27̄ + 8(adj SU3)")

# E8 ⊃ SO(16)：248 = 120 + 128
v = 120 + 128
chk("E8⊃SO(16) 分支", v == 248, "248 = 120(adj SO16) + 128(半旋量)")

# E6 ⊃ SO(10)×U(1)：78 = 45+16+16̄+1；27 = 16+10+1
v = 45 + 16 + 16 + 1
chk("E6⊃SO(10)×U(1) adjoint", v == 78, "78 = 45 + 16 + 16̄ + 1")
v = 16 + 10 + 1
