def scan_untouched(lo=225, hi=263):
    """真机读：扫 r_lo–r_hi 产物，mtime 是否早于本轮启动。
    ★排除本卷 RID 自身（本卷产物是本轮写的）。"""
    bad, scanned = [], 0
    roots = [SRC_DIR, DATA_DIR, VERDICT_DIR]
    for rd in roots:
        if not os.path.isdir(rd):
            continue
        try:
            names = os.listdir(rd)
        except Exception:
            continue
        for nm in names:
            m = re.search(r"r(2\d\d)", nm)
            if not m:
                continue
            n = int(m.group(1))
            if not (lo <= n <= hi):
                continue
            if ("r%d" % n) == RID:
                continue
            p = os.path.join(rd, nm)
            scanned += 1
            try:
                if os.path.getmtime(p) >= START_TS:
                    bad.append(nm)
            except Exception:
                pass
    return (len(bad) == 0), scanned, bad


