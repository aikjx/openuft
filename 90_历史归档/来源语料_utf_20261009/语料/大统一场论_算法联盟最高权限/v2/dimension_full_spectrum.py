def dim_str(v):
    sym = ["M","L","T","I","Θ","N","J"]
    parts = []
    for s, x in zip(sym, v):
        if x == 1: parts.append(s)
        elif x != 0: parts.append(f"{s}^{x}")
    return "·".join(parts) if parts else "无量纲"

