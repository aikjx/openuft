    anchor_list = u"- **r269（2026-10-31）·"
    anchor_sec = u"### r269 · 2026-10-31 ·"

    def after_line(t, anchor, block, tag):
        if block.split("\n")[0] in t:
            log.append("%s: 已存在，跳过" % tag)
            return t
        i = t.find(anchor)
        if i < 0:
            log.append("%s: ★锚点缺失（%s）⇒ 未插入" % (tag, anchor))
            return t
        j = t.find("\n", i)
        if j < 0:
            log.append("%s: ★锚点到文件尾，未插入" % tag)
            return t
        t = t[:j + 1] + block + "\n" + t[j + 1:]
        log.append("%s: 已插入（锚点后 %d）" % (tag, i))
        return t

    def before_line(t, anchor, block, tag):
        if block.split("\n")[0] in t:
            log.append("%s: 已存在，跳过" % tag)
            return t
        i = t.find(anchor)
        if i < 0:
            log.append("%s: ★锚点缺失（%s）⇒ 未插入" % (tag, anchor))
            return t
        t = t[:i] + block + "\n\n" + t[i:]
        log.append("%s: 已插入（锚点前 %d）" % (tag, i))
        return t

