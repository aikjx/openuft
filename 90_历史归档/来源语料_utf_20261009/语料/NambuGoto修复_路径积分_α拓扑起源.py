# 定义环面的有效势
def effective_potential(tau1, tau2, L=1.0, n_max=50):
    """
    环面上共形场论的有效势
    tau1, tau2: 环面的共形模 (实部, 虚部)
    L: 环面的周长 (σ 方向)
    n_max: 求和的截断
    """
    V = 0.0
    
    # 零点能 (使用 ζ 函数正则化)
    # E = -(π/L) Σ_{n,m} (n²/τ₂ + m²τ₂ + 2nmτ₁)^{-s/2} |_{s=-1}
    # 近似: 只保留低模
    
    for n in range(-n_max, n_max+1):
        for m in range(-n_max, n_max+1):
            if n == 0 and m == 0:
                continue
            # 环面的能量本征值
            k_sq = (2*math.pi*n/L)**2 / tau2 + (2*math.pi*m*tau2/L)**2 + 2*(2*math.pi*n/L)*(2*math.pi*m*tau2/L)*tau1
            if k_sq > 0:
                V += math.sqrt(k_sq) / 2
    
    # 面积项
    V += L**2 * tau2  # T × A, 这里 T=1 (自然单位)
    
    return V

