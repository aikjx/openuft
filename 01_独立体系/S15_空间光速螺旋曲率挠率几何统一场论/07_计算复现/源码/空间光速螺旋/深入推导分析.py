# 推导质量公式
# ============================================================
print("\n\n【4】推导质量公式")
print("-" * 70)

print("""
文档声称：m = ℏτ(α²+1)/(αc)
但实际验证此公式不正确

让我从基本原理推导正确的质量公式：
""")

# 4.1 从能量动量关系
# E² = p²c² + m²c⁴
# 对于静止粒子：E = mc²
# 从几何表示：E = ℏc√(κ²+τ²)
# 所以：m = ℏ√(κ²+τ²)/c

print("4.1 从能量动量关系推导:")
print(f"   E = mc² (静止粒子)")
print(f"   E = ℏc√(κ²+τ²) (几何表示)")
print(f"   所以: m = ℏ√(κ²+τ²)/c")

# 4.2 代入κ,τ本征解
# κ = α²ω/(c(α²+1))
# τ = αω/(c(α²+1))
# κ²+τ² = α²ω²/(c²(α²+1)²) * (α²+1) = α²ω²/(c²(α²+1))
# √(κ²+τ²) = αω/(c√(α²+1))
# m = ℏαω/(c²√(α²+1))

print("\n4.2 代入κ,τ本征解:")
print(f"   κ²+τ² = α²ω²/(c²(α²+1))")
print(f"   √(κ²+τ²) = αω/(c√(α²+1))")
print(f"   m = ℏαω/(c²√(α²+1))")

# 4.3 从文档的公式出发
# 文档声称：m = ℏτ(α²+1)/(αc)
# 代入τ = αω/(c(α²+1))
# m = ℏ·αω/(c(α²+1))·(α²+1)/(αc) = ℏω/c²

print("\n4.3 文档公式的推导:")
print(f"   m = ℏτ(α²+1)/(αc)")
print(f"   代入τ = αω/(c(α²+1)):")
print(f"   m = ℏ·[αω/(c(α²+1))]·(α²+1)/(αc)")
print(f"   m = ℏω/c²")

# 4.4 两个公式的比较
# 正确公式: m = ℏαω/(c²√(α²+1))
# 文档公式: m = ℏω/c²
# 比值: α/√(α²+1) = κ/√(κ²+τ²)

