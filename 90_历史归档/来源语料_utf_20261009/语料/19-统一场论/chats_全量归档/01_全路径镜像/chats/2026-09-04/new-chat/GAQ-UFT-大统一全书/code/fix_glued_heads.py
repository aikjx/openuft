def split_heading_body(num, rest, chap):
    s = rest.strip()
    sn = norm_q(s)
    # 0) 显式校正（引号归一化匹配）
    if chap in OVERRIDES and num in OVERRIDES[chap]:
        h, body_start = OVERRIDES[chap][num]
        bn = norm_q(body_start)
        idx = sn.find(bn)
        if idx < 0:
            return h, s  # 找不到则正文取全段（降级，预览会暴露）
        return h, s[idx:].strip()
    # 1) 【审计框 N】/【大白话】
    m = re.match(r'^【[^】]*】', s)
    if m:
        return m.group(0), s[m.end():].strip()
    # 2) 表格
    m = re.match(r'^([^|\n]+?)\|', s)
    if m and 0 < len(m.group(1).strip()) <= 42:
        return m.group(1).strip(), s[m.end():].strip()
    # 3) 行中 ### 子标题
    m = re.search(r'### ', s[:80])
    if m and m.start() > 0:
        return s[:m.start()].strip(), s[m.start():].strip()
    # 4) 正文起始标记（编号优先于加粗；标题 ≤ 30 字）
    markers = [
        (r'[\-–—]\s', 1),
        (r'\d{4}\s*年', 1),
        (r'\d+\.\s', 1),
        (r'\*\*', 1),
        (r'ch\d{2}\s', 1),
        (r'附录\s', 1),
        (r'\$\$', 1),
    ]
    for pat, _ in markers:
        mm = re.search(pat, s[:34])
        if mm and 2 <= mm.start() <= 30:
            return s[:mm.start()].strip(), s[mm.start():].strip()
    # 5) 括号 ） 结尾的短标题（标题含括号 ≤ 36 字）
    for p in range(min(len(s), 38)):
        if s[p] == '）':
            after = s[p+1:].strip()
            if len(after) >= 5 and len(s[:p+1]) <= 36:
                return s[:p+1].strip(), after
            break
    return None, s

def main():
    mode = sys.argv[1] if len(sys.argv) > 1 else 'preview'
    total_split = total_manual = 0
    for p in sorted(glob.glob(os.path.join(MS, 'ch*.md'))):
        chap = os.path.basename(p)
        with io.open(p, encoding='utf-8') as f:
            lines = f.read().split('\n')
        new_lines = []
        for ln in lines:
            m = re.match(r'^(#{2,3}) (\d+\.\d+(?:\.\d+)?) (.*)$', ln)
            if not m:
                new_lines.append(ln)
                continue
            tok, num, rest = m.group(1), m.group(2), m.group(3)
            if len(rest) <= 25:
                new_lines.append(ln)
                continue
            head, body = split_heading_body(num, rest, chap)
            if head is None:
                new_lines.append(ln)
                total_manual += 1
                if mode == 'preview':
                    print(f'{chap[:8]} | {num} | !!MANUAL!! {rest[:70]}')
                continue
            total_split += 1
            if mode == 'preview':
                print(f'{chap[:8]} | {num} | 标题: {head[:44]}')
                print(f'          |      | 正文: {body[:44]}')
            new_lines.append(f'{tok} {num} {head}')
            if body:
                new_lines.append(body)
        if mode == 'apply':
            with io.open(p, 'w', encoding='utf-8') as f:
                f.write('\n'.join(new_lines))
    print('---')
    print(f'拆分 {total_split} 处；MANUAL {total_manual} 处')
    if mode == 'apply':
        print('已应用写入')

if __name__ == '__main__':
    main()
