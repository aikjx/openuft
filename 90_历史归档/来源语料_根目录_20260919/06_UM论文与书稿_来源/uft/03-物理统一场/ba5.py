import mpmath as mp
mp.mp.dps = 30
k=mp.mpf('3.162277660168379e-4'); t=mp.mpf('2.307625500826972e-6')
hbar=mp.mpf('1.054571817e-34'); c=mp.mpf('299792458'); G=mp.mpf('6.67430e-11')
me=mp.mpf('9.1093837015e-31'); Q=me*c/hbar
lp=mp.sqrt(hbar*G/c**3); H0=mp.mpf('67.4')*1000/mp.mpf('3.085677581e22')
Rh=c/H0; alpha=mp.mpf('7.2973525693e-3'); eps0=mp.mpf('8.8541878128e-12')
e=mp.mpf('1.602176634e-19')

