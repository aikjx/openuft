# ============================================================
sec("Q1 · NG-X-2 精确 α: 整数扭转圈 + 拓扑量子化 能挑 137 吗?")
# 21号公理: α=τ/κ, α∈(0,1], 137圈=一整圈电磁扭转(直觉)
# 拓扑量子化假设: 自旋½的 4π 周期内, 电磁总扭转必须 = 2π·(m/n) (m,n整数, 分数拓扑相)
#   总扭转 = 4π·α  (21号 A 段: 4π 周期总扭转=4πα)
#   量子化条件: 4π·α = 2π·(m/n)  =>  α = m/(2n)
print(f"  拓扑量子化: 4π·α = 2π·(m/n)  ⇒  α = m/(2n)  (m,n 整数, 分数拓扑相)")
# 扫描寻找最接近 1/137.036 的有理数
target = ALPHA
best = None
for n in range(1, 200):
    m = round(2 * n * target)
    if m < 1:
        continue
    a = mpf(m) / (2 * n)
    r = rel(a, target)
    if best is None or r < best[0]:
        best = (r, m, n, a)
print(f"  最接近实测 α=1/{nstr(ALPHA_INV,6)} 的拓扑量子化解:")
print(f"    m={best[1]}, n={best[2]} ⇒ α={nstr(best[3],8)} = 1/{nstr(1/best[3],6)}")
print(f"    相对误差 = {nstr(best[0],4)}")
# 检验 n=68.5 是否为整数 (决定能否精确挑137)
n_exact = 1 / (2 * target)
print(f"  精确 1/137.036 对应 n = 1/(2α) = {nstr(n_exact,4)}  (非整数 ⇒ 拓扑量子化不能唯一挑 137)")
# 诚实结论
print(f"""
  [证明结果] 拓扑量子化把 α 约束为有理数族 α=m/(2n), 但:
    (a) 实测 1/137.036 ⇒ 需 n=68.5 非整数 ⇒ 不能唯一挑选精确 137
    (b) 最佳拟合 m=2,n=137 ⇒ α=1/137.0 (残差 2.6e-4), 给出'α 是简单有理数倒数'的部分解释
    (c) 整数圈直觉 (N=1/α=137) 只说明'扭转整圈', 不挑选数值
  [诚实修复] 21号'α=公理输入'结论维持; 拓扑量子化提供'为何α是简单有理数倒数'
             的部分解释(有理数族), 但精确 137 仍 NG-X (测量锚定)
  [状态] NG-X-2: 由'纯直觉' → '有理数族约束 (部分几何化)'  (非全解, 诚实)
""")

