p(f"  朴素 5 事件（剔 GW190828） : δτ_best = {dn_d:+.2f}% ± {dn_s:.2f}%   "
  f"95%上限(+1.96σ) = {dn_d + Z95*dn_s:+.2f}%")
p(f"  距 GR(δ=0): 边际化联合 {dm_d/dm_s:+.2f}σ ; 朴素5 {dn_d/dn_s:+.2f}σ")
