# 1.3 无量纲G的拓扑式
# G_geo = c⁶κ²/(8π)
print("\n1.3 无量纲G的拓扑式:")
print(f"   G_geo = c⁶κ²/(8π)")

# 1.4 无量纲ε₀的拓扑式
# ε₀_geo = τ/(4πc²κ) = 1/(4πc²α)
print("\n1.4 无量纲ε₀的拓扑式:")
print(f"   ε₀_geo = τ/(4πc²κ)")
print(f"   ε₀_geo = 1/(4πc²α) (化简后)")

# 1.5 Gε₀拓扑对偶恒等式
# Gε₀ = c⁴κτ/(32π²) = c²α³/(32π²(α²+1)²)
print("\n1.5 Gε₀拓扑对偶恒等式:")
print(f"   Gε₀ = c⁴κτ/(32π²)")
print(f"   Gε₀ = c²α³/(32π²(α²+1)²)")

# 验证
ge0_topology = c**2 * alpha**3 / (32 * math.pi**2 * (alpha**2 + 1)**2)
