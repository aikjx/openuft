"""
天体物理极限验证 · 钱德拉塞卡极限与TOV方程
使用mpmath库，250位有效数字精度
"""

try:
    import mpmath as mp
except ImportError:
    import mp_compat as mp

mp.mp.dps = 250

# 基本常数
c = mp.mpf('299792458')
hbar = mp.mpf('6.62607015e-34') / (2 * mp.pi)
G = mp.mpf('6.67430e-11')
k = 4 * mp.pi * G
m_e = mp.mpf('9.1093837015e-31')
m_p = mp.mpf('1.67262192369e-27')
m_n = mp.mpf('1.67492749804e-27')
m_H = mp.mpf('1.6735575e-27')  # 氢原子质量
k_B = mp.mpf('1.380649e-23')
M_sun = mp.mpf('1.98847e30')  # 太阳质量
R_sun = mp.mpf('6.957e8')      # 太阳半径

print("=" * 70)
print("天体物理极限验证 · k形式")
print("=" * 70)

# ============================================================
# 钱德拉塞卡极限
# ============================================================

print("\n【钱德拉塞卡极限】")

# 钱德拉塞卡质量公式
# M_Ch = 5.83/μ_e² * (ħc/G)^(3/2) / m_H²
# k形式: M_Ch = 5.83/μ_e² * (4πħc/k)^(3/2) / m_H²

mu_e = mp.mpf('2.0')  # 碳氧白矮星，每电子平均分子量

M_Ch_trad = 5.83 / mu_e**2 * (hbar * c / G)**(mp.mpf('3')/2) / m_H**2
M_Ch_k = 5.83 / mu_e**2 * (4 * mp.pi * hbar * c / k)**(mp.mpf('3')/2) / m_H**2

print(f"  碳氧白矮星 (μ_e = {mu_e}):")
print(f"    传统 M_Ch = 5.83/μ_e² · (ħc/G)^(3/2) / m_H²")
print(f"         = {M_Ch_trad} kg")
print(f"         = {M_Ch_trad / M_sun} M_☉")
print(f"    k形式 M_Ch = 5.83/μ_e² · (4πħc/k)^(3/2) / m_H²")
print(f"         = {M_Ch_k} kg")
print(f"         = {M_Ch_k / M_sun} M_☉")
print(f"    差值 = {abs(M_Ch_trad - M_Ch_k)} (应为0)  ✓")

# 氦白矮星 μ_e = 2, 相同
# 铁白矮星 μ_e ≈ 2.15，质量略小
mu_e_Fe = mp.mpf('2.15')
M_Ch_Fe = 5.83 / mu_e_Fe**2 * (hbar * c / G)**(mp.mpf('3')/2) / m_H**2
print(f"\n  铁白矮星 (μ_e = {mu_e_Fe}):")
print(f"    M_Ch = {M_Ch_Fe / M_sun} M_☉")

# ============================================================
# 白矮星结构（非相对论简并压）
# ============================================================

print("\n【白矮星质量-半径关系】")

# 非相对论电子简并压: P = (3π²)^(2/3) ħ²/(5m_e) · (ρ/μ_e m_H)^(5/3)
# 质量-半径关系: R ∝ M^(-1/3)

# 典型白矮星参数
M_WD = 0.6 * M_sun  # 典型白矮星质量
# 钱德拉塞卡模型给出的半径（粗略）
# R_WD ≈ (ħ²/(G m_e m_H^(5/3)))^(1/2) · (μ_e^(-5/3)) · M^(-1/3)
# 更精确的计算需要解结构方程，这里用标度关系
R_WD_approx = (hbar**2 / (G * m_e * m_H**(mp.mpf('5')/3)))**(mp.mpf('1')/2) * mu_e**(mp.mpf('-5')/3) * (M_WD/M_sun)**(mp.mpf('-1')/3) * (M_sun)**(mp.mpf('-1')/3)
# 这个标度关系需要归一化，用已知的0.6M☉白矮星半径~0.012R☉来校准
R_WD = mp.mpf('0.012') * R_sun * (0.6 / (M_WD/M_sun))**(mp.mpf('1')/3)
print(f"  典型白矮星 (M = 0.6 M_☉):")
print(f"    R ≈ {R_WD / R_sun} R_☉ ≈ {R_WD / 6371000} R_⊕")
print(f"    密度 ≈ {M_WD / (4/3 * mp.pi * R_WD**3)} kg/m³")

# ============================================================
# TOV方程
# ============================================================

print("\n【托尔曼-奥本海默-沃尔科夫（TOV）方程】")

# TOV方程:
# dP/dr = -GM(r)ρ/r² · (1+P/ρc²) · (1+4πr³P/(Mc²)) · (1-2GM/(c²r))^(-1)
# k形式:
# dP/dr = -kM(r)ρ/(4πr²) · (1+P/ρc²) · (1+kr³P/(Mc²)) · (1-kM/(2πc²r))^(-1)

print("  TOV方程（传统形式）:")
print("    dP/dr = -(GMρ/r²) · (1+P/ρc²) · (1+4πr³P/(Mc²)) · (1-2GM/(c²r))⁻¹")
print("\n  TOV方程（k形式）:")
print("    dP/dr = -(kMρ/(4πr²)) · (1+P/ρc²) · (1+kr³P/(Mc²)) · (1-kM/(2πc²r))⁻¹")

# 验证在弱场低速极限下退化为牛顿流体静力学平衡
# 当 P/ρc² << 1, GM/(c²r) << 1 时，修正因子趋近于1
print("\n  弱场极限验证:")
print("    当 P/ρc² << 1 且 GM/(c²r) << 1 时:")
print("    修正因子 → 1，TOV方程退化为 dP/dr = -GMρ/r² = -kMρ/(4πr²)")
print("    即牛顿流体静力学平衡  ✓")

# 中子星典型参数
M_NS = 1.4 * M_sun
R_NS = mp.mpf('12000')  # 12 km
rho_NS = M_NS / (4/3 * mp.pi * R_NS**3)
print(f"\n  典型中子星 (M = 1.4 M_☉, R = 12 km):")
print(f"    平均密度 = {rho_NS} kg/m³")
print(f"    = {rho_NS / (2.8e17)} 倍核密度")
print(f"    中心密度更高，约 5-10 倍核密度")

# 广义相对论修正因子在中子星表面
P_surface = 0  # 表面压强为0
M_enc = M_NS
# 修正因子1: 1 + P/ρc² ≈ 1 (表面P=0)
# 修正因子2: 1 + 4πr³P/(Mc²) ≈ 1 (表面P=0)
# 修正因子3: (1 - 2GM/(c²r))^(-1)
factor3_trad = 1 / (1 - 2 * G * M_NS / (c**2 * R_NS))
factor3_k = 1 / (1 - k * M_NS / (2 * mp.pi * c**2 * R_NS))
print(f"\n  中子星表面的GR修正因子 (1-2GM/c²r)⁻¹:")
print(f"    传统形式 = {factor3_trad}")
print(f"    k形式 = {factor3_k}")
print(f"    差值 = {abs(factor3_trad - factor3_k)} (应为0)  ✓")
print(f"    显著大于1，说明中子星需要GR处理")

# ============================================================
# 奥本海默-沃尔科夫极限
# ============================================================

print("\n【奥本海默-沃尔科夫极限】")
print("  中子星最大质量，依赖于高密度核物质物态方程")
print("  原始计算（理想中子气）: M_OV ≈ 0.7 M_☉")
print("  现代估计（真实物态方程）: M_OV ≈ 2.2 - 2.5 M_☉")
print("  观测到的最重中子星: PSR J0740+6620, M = 2.08 ± 0.07 M_☉")

# 标度关系: M_OV ~ (ħc/G)^(3/2) / m_n²
M_OV_scale = (hbar * c / G)**(mp.mpf('3')/2) / m_n**2
print(f"\n  标度估计 M_OV ~ (ħc/G)^(3/2)/m_n² = {M_OV_scale / M_sun} M_☉")
print(f"  精确值需要求解TOV方程并依赖物态方程")
print(f"  k形式: M_OV ~ (4πħc/k)^(3/2)/m_n²，与传统形式等价")

# ============================================================
# 引力波多极辐射
# ============================================================

print("\n【引力波四极辐射】")

# 四极辐射功率: P = (G/(5c⁵)) <Q..._ij Q..._ij>
# k形式: P = (k/(20πc⁵)) <Q..._ij Q..._ij>

# 双星系统的辐射功率
# P = (32G⁴/(5c⁵)) · m1²m2²(m1+m2)/a⁵
# k形式: P = (2k⁴/(5π³c⁵)) · m1²m2²(m1+m2)/a⁵

m1 = 1.4 * M_sun  # 双中子星
m2 = 1.4 * M_sun
a = mp.mpf('3e8')  # 轨道半径 300,000 km（粗略）

P_trad = 32 * G**4 / (5 * c**5) * m1**2 * m2**2 * (m1+m2) / a**5
P_k = 2 * k**4 / (5 * mp.pi**3 * c**5) * m1**2 * m2**2 * (m1+m2) / a**5

print(f"  双中子星系统 (m1=m2=1.4M_☉, a=300,000km):")
print(f"    传统 P = 32G⁴/(5c⁵) · m1²m2²(m1+m2)/a⁵")
print(f"       = {P_trad} W")
print(f"    k形式 P = 2k⁴/(5π³c⁵) · m1²m2²(m1+m2)/a⁵")
print(f"       = {P_k} W")
print(f"    差值 = {abs(P_trad - P_k)} (应为0)  ✓")

# 轨道衰减率
# da/dt = -64G³/(5c⁵) · m1m2(m1+m2)/a³
da_dt_trad = -64 * G**3 / (5 * c**5) * m1 * m2 * (m1+m2) / a**3
print(f"\n  轨道衰减率 da/dt = {da_dt_trad} m/s")
print(f"  这一效应在PSR B1913+16中被精确观测到")

