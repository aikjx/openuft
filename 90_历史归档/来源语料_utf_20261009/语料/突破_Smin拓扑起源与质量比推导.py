# n 维球体体积 (半径 R)
def sphere_volume(n, R=1.0):
    """n 维球体的体积 (n 维闭合球)"""
    if n == 0:
        return 1.0  # 0D球 = 点
    elif n == 1:
        return 2 * R  # 1D球 = 线段 [-R, R]
    elif n % 2 == 0:
        k = n // 2
        return (math.pi**k / math.factorial(k)) * R**n
    else:
        k = (n - 1) // 2
        return (2 * math.factorial(k) / math.pi**k) * (2 * R)**(2*k+1) / (2*k+1)
        # 更精确的公式:
        # V_n = (2 * π^((n-1)/2) * R^n) / (n * Γ((n-1)/2))

def sphere_volume_exact(n, R=1.0):
    """n 维球体体积的精确公式"""
    # V_n(R) = π^(n/2) / Γ(n/2+1) * R^n
    return math.pi**(n/2) / math.gamma(n/2 + 1) * R**n

def sphere_area_exact(n, R=1.0):
    """n 维球面的"面积" (即 n 维球的边界体积)"""
    # A_n(R) = 2 * π^((n+1)/2) / Γ((n+1)/2) * R^n
    # 或者: A_n = d(V_{n+1})/dR
    return 2 * math.pi**((n+1)/2) / math.gamma((n+1)/2) * R**n

