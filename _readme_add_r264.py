def main():
    raw = io.open(README, "rb").read().decode("utf-8")
    lines = raw.split("\n")

    def find_prefix(pref):
        for i, ln in enumerate(lines):
            if ln.startswith(pref):
                return i
        return -1

    def replace_first(pref, new_text):
        """命中则原地替换（幂等），未命中则插到 r263 同伴行之前。"""
        for i, ln in enumerate(lines):
            if ln.startswith(pref) and ("r264" in ln or "R264" in ln):
                lines[i] = new_text
                return i, "replaced"
        anchor = pref.replace("r264", "r263")
        j = find_prefix(anchor)
        if j >= 0:
            lines.insert(j, new_text)
            return j, "inserted"
        return -1, "no-anchor"

    before = sum(1 for ln in lines if "r264" in ln)
    ops = []
    ops.append(("源码树",) + replace_first("│   ├── TUFT-r264_", SRC_TREE))
    ops.append(("判定树",) + replace_first("├── 判定_TUFT-r264_", JUDGE_TREE))
    ops.append(("编号消歧",) + replace_first("> **编号消歧（2026-10-31 撞号第 9 次）**", DISAMBIG))
    ops.append(("增量章条目",) + replace_first("- **r264（2026-10-31）·", SUMMARY))
    for nm, idx, how in ops:
        print("  %-8s %s at L%d" % (nm, how, idx + 1))
        if idx < 0:
            print("ABORT: anchor missing ->", nm)
            return 2

    # 详节块：定位 ### r264 行，删至下一个 ### / EOF，再插入新块
    k = find_prefix("### r264 · 2026-10-31 ·")
    if k < 0:
        print("ABORT: detail anchor missing")
        return 2
    m = k + 1
    while m < len(lines) and not lines[m].startswith("### "):
        m += 1
    del lines[k:m]
    block = DETAIL.split("\n") + [""]
    for j, s in enumerate(block):
        lines.insert(k + j, s)
    print("  %-8s rewritten at L%d (%d lines)" % ("增量章详节", k + 1, len(block)))

    # 下轮指针：把「下轮从 r263/r264 复查起/起」统一改为 r265
    nfix = 0
    for i, ln in enumerate(lines):
        if ("下轮从 r263 起" in ln or "下轮从 r264 复查起" in ln
                or "下轮从 r263 复查起" in ln):
            lines[i] = ln.replace("下轮从 r263 起", "下轮从 r265 起") \
                         .replace("下轮从 r264 复查起", "下轮从 r265 复查起") \
                         .replace("下轮从 r263 复查起", "下轮从 r265 复查起")
            nfix += 1
    print("  %-8s %d 处" % ("下轮指针", nfix))

    out = "\n".join(lines)
    os.makedirs(SCRATCH, exist_ok=True)
    shutil.copy2(README, os.path.join(SCRATCH, "README.before_r264.md"))
    io.open(README, "wb").write(out.encode("utf-8"))
    print("README lines: %d -> %d" % (len(raw.split("\n")), len(lines)))
    print("r264 mentions: %d -> %d" % (before, sum(1 for ln in lines if "r264" in ln)))
    return 0


if __name__ == "__main__":
    sys.exit(main())
