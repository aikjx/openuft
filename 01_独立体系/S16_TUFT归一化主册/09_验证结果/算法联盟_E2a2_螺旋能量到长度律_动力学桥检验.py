# -*- coding: utf-8 -*-
"""
E2-a2 动力学桥：螺旋曲率-挠率能量 能否导出 Nambu-Goto 的 E=σL？

母恒等式(L1): κ²+τ² = 1/(ρ²+b²) = (ω/c)² —— 对固定螺旋是【沿弧长常数】。
检验三个命题：
 P1 螺旋管线能量 E = ∫(κ²+τ²) ds  若 κ²+τ² 沿管为常数 C0，则 E = C0·L（长度律成立）。
    数值：对圆柱螺旋 r(t)=(ρcos t,ρsin t,b t)，t∈[0,T] 直接积分。
 P2 该常数 C0 是否独立于螺距几何自动取唯一值？——扫描 ρ,b 看 C0=1/(ρ²+b²) 随几何变化
    ⇒ 若 C0 自由，则 σ=C0 仍是参数（与 J32 一致），长度律成立但 σ 不第一性。
 P3 关键反证：若能量泛函是 ∫κ² ds（纯弯曲弹性能），其极小构型是 elastica 而非直线，
    且能量不正比于长度。因此"导出 σL"要求能量密度沿管严格常数 —— 这恰由 L1 母恒等式提供。
"""
import numpy as np

# P1: 圆柱螺旋弧长元 ds/dt = sqrt(ρ²+b²)；κ=ρ/(ρ²+b²), τ=b/(ρ²+b²)
# κ²+τ²=1/(ρ²+b²) 常数；E = ∫0^T [1/(ρ²+b²)] * sqrt(ρ²+b²) dt = T/sqrt(ρ²+b²)
# 而螺旋总弧长 L = T*sqrt(ρ²+b²) ⇒ E = L/(ρ²+b²) = C0·L，C0=1/(ρ²+b²)
print("P1 螺旋管线能量（解析恒等 + 数值积分）：")
for rho,b,T in [(1.0,0.3,6.0),(1.0,1.0,6.0),(0.5,0.2,8.0)]:
    t=np.linspace(0,T,200000)
    # 位置微分速度模
    v=np.sqrt(rho**2+b**2)
    kap=rho/(rho**2+b**2); tau=b/(rho**2+b**2)
    dens=kap**2+tau**2
    E_num=np.trapezoid(dens*np.full_like(t,v),t)   # ∫ dens ds
    L=v*T
    E_pred=dens*L
    print(f"  ρ={rho},b={b}: κ²+τ²={dens:.6f}(常数), E数值={E_num:.5f}, C0·L={E_pred:.5f}, E/L={E_num/L:.6f}")

# P2: C0=1/(ρ²+b²) 随几何自由
print("\nP2 C0=1/(ρ²+b²) 随螺旋几何扫描：")
for rho,b in [(1,.1),(1,.5),(1,1),(2,1)]:
    print(f"  ρ={rho},b={b}: σ=C0={1/(rho**2+b**2):.5f}")
print("  ⇒ 长度律成立，但弦张力 σ 随几何自由取值（J32：参数不第一性）")

# P3: 对照纯弹性能 ∫κ² ds：圆/直线对比，证明不是"长度"
print("\nP3 对照：弯曲弹性能 ∫κ² ds 不正比于长度")
# 直线 κ=0 → E=0（任意长度）；半径R圆弧 κ=1/R，E=∫κ²ds=L/R²
R=1.0
for Larc in [1.0,2.0,3.0]:
    print(f"  半径{R}圆弧 L={Larc}: 弯曲能={Larc/R**2:.2f}（虽∝L但要求固定曲率，直线为0，非NG弦张力）")
print("  螺旋母恒等式给的是『沿管常数正能密度』，这正是 NG σ 的几何对应——但需管截面/外尺度定σ")
