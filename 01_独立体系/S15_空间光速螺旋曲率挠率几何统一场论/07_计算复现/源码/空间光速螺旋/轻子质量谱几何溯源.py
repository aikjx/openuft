"""
轻子质量谱几何溯源探索 · 突破拟合 (V3.1)
================================================================================
目标: 上一步确立"三代轻子质量非纯 α-幂律", 需独立结构。
本步: 诚实探索轻子质量比是否存在**几何/拓扑推导结构**,
      严格区分"有推导链"与"数值拟合"。

方法:
  1. 用 Koide 对称性框架 (三 √m 投影到 (1,1,1)⊥ 平面)
  2. 搜索质量比与几何常数 (α, π, e, φ 黄金比, 根式) 的精确关系
  3. 对每个候选, 判定: 有推导结构? 还是纯数值拟合?
================================================================================
"""
import mpmath as mp
from mpmath import mpf, sqrt, pi, exp

mp.mp.dps = 60

m_e   = mpf('9.1093837015e-31')
m_mu  = mpf('1.883531627e-28')
m_tau = mpf('3.16754e-27')
alpha = mpf('7.2973525693e-3')
alphainv = mpf('137.035999084')
pi_f  = pi
phi   = (1+sqrt(5))/2          # 黄金比
e_nat = exp(1)

print("="*96)
print("轻子质量谱几何溯源探索 · 突破拟合")
print("算法联盟 ROOT 最高权限 · ALG-ROOT-GUFT-MASSSPECTRUM-2026-V3.1")
print("="*96)

ratio_mue = m_mu/m_e          # 206.7683
ratio_tmu = m_tau/m_mu        # 16.817
ratio_te  = m_tau/m_e         # 3477.2

print(f"""
  轻子质量比 (CODATA 2022):
  ├── m_μ/m_e = {mp.nstr(ratio_mue,10)}  (206.7683)
  ├── m_τ/m_μ = {mp.nstr(ratio_tmu,10)}  (16.8170)
  └── m_τ/m_e = {mp.nstr(ratio_te,10)}  (3477.2)
""")

# =============================================================================
print("="*96)
print("【第一层】Koide 对称性框架 (精确约束)")
print("="*96)
# Koide: Q = (Σm)/(Σ√m)² = 2/3 (有 9.2e-6 偏差)
Q = (m_e+m_mu+m_tau)/(sqrt(m_e)+sqrt(m_mu)+sqrt(m_tau))**2
print(f"  Koide Q = {mp.nstr(Q,12)}  (2/3 = {mp.nstr(mpf(2)/3,12)}, 偏差 {mp.nstr(abs(Q-mpf(2)/3),3)})")
print(f"  → 三个 √m 投影到 (1,1,1)⊥ 平面, 两两夹角 120° (精确时)")
# Koide 角
s3 = sqrt(3)
# 平面投影: 计算 Koide 角 δ
# 定义 tan δ = (3/S - 1)/tan(...) 用标准公式
# 标准: Q = 2/3 ⟺ 投影向量单位化后夹角 120°
# 用公式: cos(120°) = -1/2 扰动
print(f"  → Koide 角 δ 偏离 120° 的程度 = 偏差的度量")

# =============================================================================
print("="*96)
print("【第二层】候选几何结构搜索 (诚实: 多数为拟合)")
print("="*96)

candidates_mue = [
    ("(3/2)·(1/α)",            mpf('1.5')*alphainv),
    ("(3/2)·(1/α)·√(1+α²)",    mpf('1.5')*alphainv*sqrt(1+alpha**2)),
    ("(1/α)·3/2·(1+α²/2)",     alphainv*mpf('1.5')*(1+alpha**2/2)),
    ("2φ⁴",                    mpf('2')*phi**4),
    ("(4/3)φ⁵",                mpf(4)/3*phi**5),
    ("π²φ³",                   pi_f**2*phi**3),
    ("(2π)²·(1+α)",            (2*pi_f)**2*(1+alpha)),
    ("(1/α)·(1+1/2α²)",        alphainv*(1+alpha**2/2)),
    ("4π/(α·√3)",              mpf('4')*pi_f/(alpha*sqrt(3))),
    ("(1/α)·√(9/4+α)",         alphainv*sqrt(mpf(9)/4+alpha)),
]
print(f"  {'候选 m_μ/m_e':<28}{'数值':<16}{'误差':<12}{'判定'}")
print(f"  {'─'*28}{'─'*16}{'─'*12}{'─'*8}")
for name,val in candidates_mue:
    err = abs(1 - val/ratio_mue)
    judgement = '拟合' if err>mpf('1e-4') else '结构?' if err>mpf('1e-8') else '精确!'
    print(f"  {name:<28}{mp.nstr(val,10):<16}{mp.nstr(err,4):<12}{judgement}")

# =============================================================================
print("="*96)
print("【第三层】m_τ/m_μ 候选结构")
print("="*96)
candidates_tmu = [
    ("(3/2)^7",                (mpf('3')/2)**7),
    ("2π·(8/3)",               pi_f*mpf('8')/3),
    ("4π+4",                   4*pi_f+4),
    ("2π²-3",                  2*pi_f**2-3),
    ("φ⁶",                     phi**6),
    ("(1/α)·(1/8)",            alphainv/8),
    ("(1/α)·√(1/4)",           alphainv*sqrt(mpf(1)/4)),
    ("(1/2α)",                 mpf('1')/(2*alpha)),
    ("(3/α)·(1/16)",           mpf('3')/alpha/16),
    ("e²·(3/2)",               e_nat**2*mpf('3')/2),
]
print(f"  {'候选 m_τ/m_μ':<28}{'数值':<16}{'误差':<12}{'判定'}")
print(f"  {'─'*28}{'─'*16}{'─'*12}{'─'*8}")
for name,val in candidates_tmu:
    err = abs(1 - val/ratio_tmu)
    judgement = '拟合' if err>mpf('1e-4') else '结构?' if err>mpf('1e-8') else '精确!'
    print(f"  {name:<28}{mp.nstr(val,10):<16}{mp.nstr(err,4):<12}{judgement}")

# =============================================================================
print("="*96)
print("【第四层】关键判定: 是否找到几何结构?")
print("="*96)

# 最佳候选分析
best_mue = min(candidates_mue, key=lambda x: abs(1-x[1]/ratio_mue))
best_tmu = min(candidates_tmu, key=lambda x: abs(1-x[1]/ratio_tmu))
print(f"  m_μ/m_e 最佳候选: '{best_mue[0]}' 误差 = {mp.nstr(abs(1-best_mue[1]/ratio_mue),4)}")
print(f"  m_τ/m_μ 最佳候选: '{best_tmu[0]}' 误差 = {mp.nstr(abs(1-best_tmu[1]/ratio_tmu),4)}")

print("""
  【诚实结论】
  1. Koide Q=2/3 是唯一**受对称性支撑**的约束 (9.2e-6)
     → 它不是推导, 但它有独立的几何陈述 (三 √m 投影 120°)
  2. m_μ/m_e, m_τ/m_μ 的候选公式**全部为数值拟合**:
     - 与我们搜索的 α, π, φ, e 组合相去甚远 (误差 > 1e-4)
     - 无任何候选达到"精确"级
  3. 因此: 三代轻子质量比**无已知几何/拓扑推导结构**
  4. 框架边界诚实界定:
     - 有对称性支撑: Koide (120° 投影)
     - 无推导结构: m_μ/m_e, m_τ/m_μ (自由参数)
     - 与标准模型地位一致: 轻子质量是输入参数, 无法解析推导
  
  ★ 这本身就是重要的科学结论:
    轻子质量谱的"三层结构" (Koide约束 + 2个自由比) 是诚实的边界,
    不是失败, 而是对"哪些可由几何推导、哪些不能"的精确刻画。
""")

