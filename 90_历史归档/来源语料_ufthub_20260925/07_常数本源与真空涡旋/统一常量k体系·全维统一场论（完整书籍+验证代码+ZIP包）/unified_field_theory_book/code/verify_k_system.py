#!/usr/bin/env python3
"""
统一常量k体系 · 全维精算验证代码库
基础常数定义与k体系核心验证
使用mpmath库，250位有效数字精度
"""

try:
    import mpmath as mp
except ImportError:
    import mp_compat as mp

# 设置精度为250位有效数字
mp.mp.dps = 250

# ============================================================
# 第一部分：基本物理常数（CODATA 2022推荐值）
# ============================================================

# 光速（精确值，SI定义）
c = mp.mpf('299792458')  # m/s

# 普朗克常数（精确值，SI定义）
h = mp.mpf('6.62607015e-34')  # J·s
hbar = h / (2 * mp.pi)  # 约化普朗克常数

# 万有引力常数（CODATA 2022，含不确定度）
G = mp.mpf('6.67430e-11')  # m^3 kg^-1 s^-2

# 真空介电常数（由μ0和c导出，μ0现在是测量值）
# 注意：2019年SI修订后，μ0不再是精确值，而是有不确定度
mu0 = mp.mpf('1.25663706212e-6')  # H/m (N/A^2)
epsilon0 = 1 / (mu0 * c**2)  # F/m

# 基本电荷（精确值，SI定义）
e = mp.mpf('1.602176634e-19')  # C

# 电子质量
m_e = mp.mpf('9.1093837015e-31')  # kg

# 质子质量
m_p = mp.mpf('1.67262192369e-27')  # kg

# 中子质量
m_n = mp.mpf('1.67492749804e-27')  # kg

# 玻尔兹曼常数（精确值，SI定义）
k_B = mp.mpf('1.380649e-23')  # J/K

# 阿伏伽德罗常数（精确值，SI定义）
N_A = mp.mpf('6.02214076e23')  # mol^-1

# 原子质量单位
u = mp.mpf('1.66053906660e-27')  # kg

# 哈勃常数（普朗克2018 + 外部数据，约67.4 km/s/Mpc）
H0 = mp.mpf('67.4') * 1000 / (mp.mpf('3.0856775814913673e22'))  # 1/s

# 宇宙学常数对应的暗能量密度参数
Omega_Lambda = mp.mpf('0.689')
Omega_m = mp.mpf('0.311')

# ============================================================
# 第二部分：k体系定义
# ============================================================

# 统一常量k = 4πG（引力常数有理化）
k = 4 * mp.pi * G

# 电磁耦合系数k' = 1/ε0
k_prime = 1 / epsilon0

print("=" * 70)
print("统一常量k体系 · 基础常数验证")
print("=" * 70)
print(f"\n【基本常数】")
print(f"  光速 c = {c} m/s")
print(f"  约化普朗克常数 ħ = {hbar} J·s")
print(f"  万有引力常数 G = {G} m^3 kg^-1 s^-2")
print(f"  真空介电常数 ε0 = {epsilon0} F/m")
print(f"  真空磁导率 μ0 = {mu0} H/m")
print(f"  基本电荷 e = {e} C")

print(f"\n【k体系定义】")
print(f"  统一常量 k = 4πG = {k} m^3 kg^-1 s^-2")
print(f"  电磁耦合 k' = 1/ε0 = {k_prime} m/F")

# ============================================================
# 第三部分：量纲验证
# ============================================================

print(f"\n【量纲验证】")
print(f"  [k] = [4πG] = L^3 M^-1 T^-2  ✓")
print(f"  [k'] = [1/ε0] = M L^3 T^-4 I^-2  ✓")

# 验证 k'η² 的量纲等于 k 的量纲
# η = Q/M, [η] = I T M^-1
# [k'η²] = (M L^3 T^-4 I^-2) * (I² T² M^-2) = L^3 M^-1 T^-2 = [k]
print(f"  量纲相容条件 [k'η²] = [k]  ✓ (代数验证通过)")

# ============================================================
# 第四部分：数值验证 - k形式与传统形式等价性
# ============================================================

print(f"\n【等价性验证】")

# 牛顿引力：F = GMm/r² = kMm/(4πr²)
M_test = mp.mpf('1.0')  # kg
m_test = mp.mpf('1.0')  # kg
r_test = mp.mpf('1.0')  # m

F_traditional = G * M_test * m_test / r_test**2
F_k_form = k * M_test * m_test / (4 * mp.pi * r_test**2)
diff_F = abs(F_traditional - F_k_form)
print(f"  牛顿引力等价性: |F_G - F_k| = {diff_F} (应为0)  ✓")

# 库仑力：F = (1/4πε0)Qq/r² = k'Qq/(4πr²)
Q_test = e
q_test = e
F_em_traditional = (1 / (4 * mp.pi * epsilon0)) * Q_test * q_test / r_test**2
F_em_k_form = k_prime * Q_test * q_test / (4 * mp.pi * r_test**2)
diff_F_em = abs(F_em_traditional - F_em_k_form)
print(f"  库仑力等价性: |F_ε0 - F_k'| = {diff_F_em} (应为0)  ✓")

# ============================================================
# 第五部分：精细结构常数验证
# ============================================================

print(f"\n【精细结构常数】")
alpha = e**2 / (4 * mp.pi * epsilon0 * hbar * c)
print(f"  α = e²/(4πε0ħc) = {alpha}")
print(f"  1/α = {1/alpha}")
print(f"  CODATA推荐值 1/α ≈ 137.035999084  ✓")

# 验证：废除 α = k m_p²/(ħc) 恒等式
alpha_wrong = k * m_p**2 / (hbar * c)
print(f"\n  【循环论证检验】")
print(f"  错误恒等式 α = k m_p²/(ħc) = {alpha_wrong}")
print(f"  正确 α = {alpha}")
print(f"  二者比值 = {alpha_wrong/alpha} (远不等于1，证明该恒等式错误)  ✓")
print(f"  结论：α = k m_p²/(ħc) 已废除，仅使用标准定义")

# ============================================================
# 第六部分：高能渐近耦合假设检验
# ============================================================

print(f"\n【高能渐近耦合假设检验】")
# 检验 ħ = 4πkc 在低能SI单位下是否成立
lhs = hbar
rhs = 4 * mp.pi * k * c
ratio = lhs / rhs
print(f"  ħ = {lhs} J·s")
print(f"  4πkc = {rhs} (量纲: L^4 M^-1 T^-3，与ħ量纲不同!)")
print(f"  比值 ħ/(4πkc) = {ratio}")
print(f"  结论：在低能SI单位下，ħ ≠ 4πkc，量纲都不匹配！")
print(f"  该式仅作为普朗克能标唯象近似，低能区严格失效  ✓")

# ============================================================
# 第七部分：前期闭环公式数值检验
# ============================================================

print(f"\n【前期闭环公式数值检验】")
# 检验 ρ_DM = c^5/(ħk²) 的数值
rho_DM_wrong = c**5 / (hbar * k**2)
rho_critical = 3 * H0**2 / (8 * mp.pi * G)
print(f"  错误公式 ρ_DM = c⁵/(ħk²) = {rho_DM_wrong} kg/m³")
print(f"  宇宙临界密度 ρ_c = {rho_critical} kg/m³")
print(f"  比值 = {rho_DM_wrong/rho_critical} (约120个数量级!)")
print(f"  结论：该闭环公式完全错误，已废除  ✓")

# ============================================================
# 第八部分：电荷-质量比η
# ============================================================

print(f"\n【电荷-质量比 η = Q/M】")
eta_e = e / m_e
eta_p = e / m_p
print(f"  电子 η_e = e/m_e = {eta_e} C/kg")
print(f"  质子 η_p = e/m_p = {eta_p} C/kg")
print(f"  η_e/η_p = {eta_e/eta_p} (≈ m_p/m_e ≈ 1836)")

# 量纲相容数值检验
# k' * η² 应与 k 具有相同量纲（数值上不一定相等，因为η依赖粒子）
print(f"\n  量纲相容数值检验:")
print(f"  k'η_e² = {k_prime * eta_e**2} (量纲同k)")
print(f"  k = {k}")
print(f"  比值 k'η_e²/k = {k_prime * eta_e**2 / k}")
print(f"  (量纲相同但数值不同，因为η是粒子依赖的拟合参数)  ✓")

# ============================================================
# 第九部分：输出总结
# ============================================================

print(f"\n{'=' * 70}")
print("验证总结")
print("=" * 70)
print("  ✓ k = 4πG 定义正确，与传统形式完全等价")
print("  ✓ k' = 1/ε0 定义正确，库仑力形式等价")
print("  ✓ 量纲相容条件 [k'η²] = [k] 成立")
print("  ✓ 精细结构常数使用标准定义，错误恒等式已废除")
print("  ✓ ħ = 4πkc 低能不成立，仅为高能唯象假设")
print("  ✓ 前期闭环公式数值偏差约120个数量级，已废除")
