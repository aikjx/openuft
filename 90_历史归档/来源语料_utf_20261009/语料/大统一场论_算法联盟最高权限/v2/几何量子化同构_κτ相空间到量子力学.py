for n in [2,3,4]:
    tau_n = tau1/n
    pn = hbar*tau_n
    an = a0*n**2
    Ekin = pn**2/(2*mu)
    Vn = -e_el**2/(4*pi_f*eps0*an)
    Et = Ekin+Vn
