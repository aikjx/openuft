# 从这两个 E_n 的表达式, 可以反推 κ_n 和 τ_n

def kappa_tau_from_energy(E_n, m=mu):
    """从能级 E_n 反推 κ 和 τ (假设 α = τ/κ)"""
    # E = mc²/√(1+ε²), ε = τ/κ = α (对于基态)
    # 但对于激发态, ε ≠ α!
    
    # 对于氢原子, ε_n 由 Dirac 公式给出:
    # ε_n = √((mc²/E_n)² - 1)
    eps_n = sqrt((m*c**2/E_n)**2 - 1)
    
    # 需要另一个约束来分别确定 κ 和 τ
    # 使用: ω_n = mc²/ℏ (对于所有态? 不, ω_n 不同)
    # 实际上: ω_n = E_n/ℏ (能级 → 频率)
    
