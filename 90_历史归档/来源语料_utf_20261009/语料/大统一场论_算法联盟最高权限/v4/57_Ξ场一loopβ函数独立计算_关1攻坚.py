put("    · '四力=Ξ 的四维投影' + 'n_q=3 子螺旋相干' (文字叙述, 无规范顶点, 无费米子)")
put("    ⇒ 52号 C3 的 β 函数系数是**借来的 SM 结构**, 不是 Ξ 场自己跳出来的。")

sec("[Q4] 独立算出的标量 β_λ → 与 52号 β_S 对比 (数值)")
# 真正独立算出的: 标量自作用 β_λ (无规范). 用教科书锚实标量 φ⁴ 作数值例, 复标量同号同量级.
