# ============================================================================
# W1  背景额外源：从叠加闭包提取 ρ_φ
# ============================================================================
I("W1 逆变分问题的目标：提取叠加闭包隐含的背景额外密度 ρ_φ")


def extra_term(rho, rhodot, rho_c, rho_min):
    """[C] 脚本式(19) 的额外项（量纲 1/s²），加到 3H² 上"""
    return (ALPHA / rho_c) * rhodot**2 / (rho + rho_min)


def rho_phi_of(rho, rhodot, rho_c, rho_min):
    """额外项折算为等效质量密度 kg/m^3： 8πG·ρ_φ = 额外项"""
    return extra_term(rho, rhodot, rho_c, rho_min) / (8 * mp.pi * G)


rhodot0 = -3 * H0 * RHO_M0                    # 物质主导连续性方程
rho_phi_A = rho_phi_of(RHO_M0, rhodot0, RHO_C_A, RHO_MIN_A)
rho_phi_C = rho_phi_of(RHO_M0, rhodot0, RHO_C_C, RHO_MIN_C)
I("W1 z=0（物质主导, ρ̇=-3Hρ）：ρ_matter=%s kg/m^3；"
  "[A][B] 档 ρ_φ=%s（=ρ_matter×%s）；[C] 档 ρ_φ=%s（=ρ_matter×%s）"
  % (n(RHO_M0), n(rho_phi_A), n(rho_phi_A / RHO_M0),
     n(rho_phi_C), n(rho_phi_C / RHO_M0)))

# ============================================================================
# W2  逆变分问题的【通解】：P = g(ρ)Y + C(ρ)√Y 满足 2Y P_Y - P = gY
#     用数值微分严格验证（不靠声称）
# ============================================================================
I("W2 通解存在性：验证 P=g·Y+C·√Y 满足 k-essence 能量密度方程 ρ_φ=2Y·P_Y-P")

G_FUNC = mp.mpf("1")            # 取 g(ρ)=1 归一化（结论与 g 的具体形式无关）
C_FUNC = mp.mpf("0.7")          # 取任意 C(ρ)=0.7 演示


def P_of_Y(Y):
    return G_FUNC * Y + C_FUNC * mp.sqrt(Y)


def rho_phi_from_P(Y, h):
    """数值算 2Y·P_Y - P（中心差分求 P_Y）"""
    PY = (P_of_Y(Y + h) - P_of_Y(Y - h)) / (2 * h)
    return 2 * Y * PY - P_of_Y(Y)


Y0 = mp.mpf("1")
h0 = mp.mpf("1e-30")
target = G_FUNC * Y0                       # 目标 ρ_φ = g·Y
got = rho_phi_from_P(Y0, h0)
res2 = abs(got - target) / abs(target)
if res2 < mp.mpf("1e-40"):
    P_("W2 【存在性 PASS】：P(Y,ρ)=g(ρ)Y+C(ρ)√Y 精确满足 2Y·P_Y-P=gY（相对残差=%s）"
       "⇒ 叠加闭包【确实可以由 k-essence 型作用量实现】，不能笼统说'不存在作用量'" % n(res2))
else:
    F_("W2 通解验证失败，残差=%s" % n(res2))

B("W2b 诚实修正（针对续篇三/四的预判）：此前按'取模不可微'预判作用量【不存在】，"
  "该论证过弱——可用 √(X²+ε²) 光滑逼近绕开。逆变分问题的正确答案是"
  "'存在，但含任意函数 C(ρ)'，属【欠定】而非【不存在】")

# ============================================================================
# W3  欠定：σ 不被背景约束 ⇒ w、c_s²、宇宙加速度全都不确定
#     w = 1+σ,  c_s² = 1+σ/2,  p_φ = ρ_φ(1+σ)
# ============================================================================
I("W3 欠定：同一条背景方程对应无穷多理论")

# 今天的 Y（由 ρ_φ = gY 反定标，仅用于 σ 参数化的自洽演示）
# 取 [A][B] 档（额外项与物质同量级，差异最显著）
RHO_PHI = rho_phi_A
H2_0 = 8 * mp.pi * G * (RHO_M0 + RHO_PHI) / 3        # 背景 H² 由构造固定（所有候选相同）

I("W3 固定背景：H²=%s（所有候选共用）；ρ_φ=%s；改变 σ 不改变 H²，只改变压强"
  % (n(H2_0), n(RHO_PHI)))
I("W3 %-8s %-14s %-14s %-14s %-14s" % ("σ", "w_φ=1+σ", "c_s²=1+σ/2", "ä/a [1/s²]", "q"))

