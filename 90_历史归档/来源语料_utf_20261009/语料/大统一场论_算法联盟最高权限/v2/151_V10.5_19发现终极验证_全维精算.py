    total+=1
    err=abs(computed-ref)/abs(ref) if ref!=0 else abs(computed)
    if level=='S': S_count+=1
    else: B_count+=1
    st="✓" if err<1e-30 else ("~" if err<1e-10 else "✗")
    if err>=1e-10 and level=='S': fail_count+=1
    print(f"  [{level}] {name}")
    print(f"       误差 = {nstr(err,8)} {st}")
    return err<1e-10

