# -*- coding: utf-8 -*-
"""真空纵波 = 电荷对流束缚模式（螺旋几何导出色散参数）
问题：42 号发现 UFE-2 纵波 ω=V_zk 线性 vs Langmuir ω_p 截止冲突。
深入：ω=V_zk (<c) 意味着波被电荷拖曳，非自由传播真空波。
闭合：电荷沿螺旋运动（旋转 ω_r、轴向 v_z），纵向电荷密度波：
  空间周期 λ_z = 螺距 = 2π·v_z/ω_r → k=ω_r/v_z
  静止系纵向振荡频率 ω = k·v_z = ω_r
  → 色散 ω=V_zk 不是假设，是螺旋几何导出：ω=ω_r(旋转频率), k=ω_r/v_z
  → 纵波是电荷的束缚对流模式：B=0, S=0(不辐射), 频率=旋转频率, 传播=轴向速度
标准电动力学无此结构：运动电荷场振荡要么辐射(横,S≠0)要么准静态(不振荡)
"""
import numpy as np
me=9.1093837015e-31; e=1.602176634e-19; c=299792458.0; eps0=8.8541878128e-12
f=me/(2*e)

print("== 螺旋几何导出纵波色散参数 ==")
def spiral(vzfrac, B_T):
    """回旋电子束：磁场 B 给回旋频率 ω_c=eB/me"""
    w_r=e*B_T/me
    vz=vzfrac*c
    lam_z=2*np.pi*vz/w_r
    k=2*np.pi/lam_z
    w=w_r                       # ω = ω_r = 旋转频率
    E=f*vz*w                    # E 幅值 (A0~vz)
    u=0.5*eps0*E**2
    print(f"  B={B_T:.1f}T, v_z={vzfrac:.2f}c:")
    print(f"    ω_r=eB/m_e={w_r:.3e} rad/s (ν={w_r/2/np.pi:.3e} Hz)")
    print(f"    λ_z=2πv_z/ω_r={lam_z:.3e} m (螺距)")
    print(f"    k=ω_r/v_z={k:.3e} 1/m, ω=ω_r={w:.3e} → 色散 ω=kv_z ✓ (ω_r=kv_z)")
    print(f"    E_amp=f·v_z·ω={E:.3e} V/m, 储能 u={u:.3e} J/m³")
    print(f"    检验: k·v_z={k*vz:.3e} vs ω_r={w_r:.3e} → 比值={k*vz/w_r:.4f}\n")

print("--- 回旋电子束 (典型加速器) ---")
spiral(0.1, 1.0)   # 1T 回旋
spiral(0.3, 5.0)   # 5T 强场
spiral(0.01, 0.1)  # 弱场慢束

print("== 结论 ==")
print(" ① ω=V_zk 由螺旋几何导出：ω=ω_r(旋转频率), k=ω_r/v_z, λ_z=螺距")
print(" ② 纵波是电荷束缚对流模式（非自由传播真空波）：B=0, S=0, 慢于光")
print(" ③ 与 Langmuir 冲突的根源：UFE-2 纵波是单电荷对流模式(无集体 ω_p)，")
print("    Langmuir 是等离子体集体振荡(有 ω_p)——两者本不同源，42 号判据 C1 应修正为")
print("    '单电荷束流近场束缚纵振荡'而非'等离子体色散'")
print(" ④ 可测判据(修正版)：回旋/同步辐射源近场存在 B=0、S=0、E∥v_z、频率=ω_r 的")
print("    束缚纵向振荡——标准电动力学不预言此结构(其场振荡要么辐射横波要么准静态)")
