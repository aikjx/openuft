    # κ_n² + τ_n² = (ω_n/c)²
    # τ_n/κ_n = ε_n (从 ε = τ/κ)
    
    # 解: κ_n = (ω_n/c) / √(1+ε_n²)
    #      τ_n = ε_n · κ_n
    
    kappa_n = (omega_n / c) / sqrt(1 + eps_n**2)
    tau_n = eps_n * kappa_n
    
    return kappa_n, tau_n, eps_n

