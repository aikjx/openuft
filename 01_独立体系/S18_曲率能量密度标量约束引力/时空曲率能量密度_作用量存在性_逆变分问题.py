MPC = mp.mpf("3.0856775814913673e22")

H0 = mp.mpf("70") * mp.mpf("1000") / MPC
RHO_CRIT_M = 3 * H0**2 / (8 * mp.pi * G)
OMEGA_M = mp.mpf("0.31")
RHO_M0 = OMEGA_M * RHO_CRIT_M                 # 今天物质质量密度 kg/m^3
OMEGA_L = mp.mpf("0.69")
LAMBDA = 3 * OMEGA_L * H0**2 / C**2

ALPHA = mp.mpf("1.87")
# 两档参数锚（续篇四裁决，统一折算到质量密度 kg/m^3）
RHO_C_A = mp.mpf("1e-9") / C**2
RHO_MIN_A = mp.mpf("1e-30") / C**2
RHO_C_C = mp.mpf("1e18")
RHO_MIN_C = mp.mpf("1")

CNT = {"PASS": 0, "FAIL": 0, "BOUNDARY": 0, "INFO": 0}


def P_(m):
    print("[PASS] " + m)
    CNT["PASS"] += 1


def F_(m):
    print("[FAIL] " + m)
    CNT["FAIL"] += 1


def B(m):
    print("[BOUNDARY] " + m)
    CNT["BOUNDARY"] += 1


