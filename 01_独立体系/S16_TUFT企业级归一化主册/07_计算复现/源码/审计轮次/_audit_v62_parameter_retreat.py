def sigma_from_band(lo, hi):
    return (hi - lo) / (2.0 * Z90)


def best_fit(rows):
    """flat-prior 高斯独立残差最佳拟合：d_hat=加权均值, sig=1/sqrt(sum 1/sig^2)。"""
    r = [(n, d, sigma_from_band(lo, hi)) for n, d, lo, hi in rows]
    P = sum(1.0 / (s * s) for _, _, s in r)
    d_hat = sum(d / (s * s) for _, d, s in r) / P
    sig = 1.0 / math.sqrt(P)
    return d_hat, sig, r


