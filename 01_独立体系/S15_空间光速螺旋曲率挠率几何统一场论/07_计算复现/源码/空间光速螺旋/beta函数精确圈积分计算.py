# 计算修正积分
# 定义无量纲变量: x = k/k₀, 使得积分变为无量纲
# m = m_e, k₀ = m_ec/ℏ, m²c² = k₀²ℏ²
# 
# 在 ZUFT 中, ρ = R_C/√(1+α²) = 1/(k₀√(1+α²))
# 所以 kρ = x/√(1+α²) 其中 x = k/k₀

def integrand_correction(x):
    """被积函数: x·[F(x)² - 1]/(x²+1)²"""
    k_over_k0 = x
    krho = k_over_k0 / sqrt(1 + alpha_0**2)  # kρ = x/√(1+α²)
    F_sq = besselj(0, krho)**2
    return x * (F_sq - 1) / (x**2 + 1)**2

