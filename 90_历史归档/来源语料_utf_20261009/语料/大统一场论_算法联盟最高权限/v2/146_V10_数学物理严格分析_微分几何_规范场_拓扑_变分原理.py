# B_z = (-Rsinθ/L)(-sinθ) - (Rcosθ/L)(-cosθ) = R(sin²θ+cos²θ)/L = R/L
# B_x = (Rcosθ/L)(0) - (h/L)(-sinθ) = h·sinθ/L
