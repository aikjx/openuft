from mpmath import mp, mpf, sqrt, pi
mp.dps = 200

c     = mpf('299792458')
hbar  = mpf('1.0545718176461565e-34')
alpha = mpf('1')/mpf('137.035999084')
m_e   = mpf('9.1093837015e-31')

def rel_err(a, b):
    return mp.fabs(a - b) / mp.fabs(b) if b != 0 else mp.fabs(a)

SEP = "=" * 70
SUB = "-" * 70

print(SEP)
print("  螺旋时空大统一场论 V2 — 可测试预言探索 (弱 PRED 级)")
print("  无需新公理: 探索框架内是否存在可实验检验的预言")
print(SEP)

# ===== 基础几何参数 =====
kappa = m_e * c / (hbar * sqrt(1 + alpha**2))
tau   = alpha * kappa
s2    = kappa**2 + tau**2  # = (m_e*c/hbar)²

print(f"\n  基础几何: κ = {mp.nstr(kappa,10)}, τ = {mp.nstr(tau,10)}")
print(f"  κ²+τ² = {mp.nstr(s2,12)} m⁻² = (m_e*c/ℏ)²")

# ====================================================================
# 方向 1: 修正色散关系 (Modified Dispersion Relation)
# ====================================================================
print(f"\n{SUB}")
print("  方向 1: 统一波动方程的色散关系")
print(SUB)

# 统一波动方程: □ψ = (κ²+τ²)ψ
# 对平面波 ψ = A·e^{i(kx-ωt)}:
# □ψ = (-ω²/c² + k²)ψ = (κ²+τ²)ψ
# 所以 ω² = c²(k² - κ² - τ²) = c²k² - c²(κ²+τ²)

# 这给出: ω = c√(k² - (κ²+τ²))
# 当 k² >> κ²+τ² 时: ω ≈ ck - c²(κ²+τ²)/(2k)
# 群速度: v_g = dω/dk = ck/√(k² - κ² - τ²)

# 与标准色散关系 ω² = c²k² 比较:
# 修正项: Δω = ω - ck ≈ -c²(κ²+τ²)/(2ck) = -(m_e²c³)/(2ℏ²k)

# 这给出能量依赖的光子速度:
# v_phase = ω/k = c√(1 - (κ²+τ²)/k²) < c

# 但 κ²+τ² = (m_e·c/ℏ)² ~ (10¹² m⁻¹)² = 10²⁴ m⁻²
# 对可见光 (λ~500nm): k = 2π/λ ~ 10⁷ m⁻¹
# κ²+τ²/k² ~ 10²⁴/10¹⁴ = 10¹⁰ → 修正巨大!
# 这显然不对 — 框架不能这样用于光子

# 正确解释: κ,τ 是粒子依赖的
# 对光子 (无质量): κ_γ = τ_γ = 0, 无修正
# 对电子: κ_e, τ_e 给出标准色散关系 ω² = c²k² + (m_e c²/ℏ)²

print(f"\n  统一波动方程 □ψ = (κ²+τ²)ψ")
print(f"  色散关系: ω² = c²k² - c²(κ²+τ²)")
print(f"  相速度: v_phase = c√(1 - (κ²+τ²)/k²)")

# 检查: 若 κ,τ 是普适常数, 对光子 (k >> κ):
# 注意: k 必须远大于 κ,τ 才能得到实数 ω
# 对电子 Compton 波长: λ_C = h/(m_e c) ≈ 2.43e-12 m
# 取 k 对应 λ = 10⁻¹⁵ m (远小于 Compton 波长)
k_test = 2*pi / mpf('1e-15')  # 1 fm 波长
omega_std = c * k_test
# ω² = c²(k² - κ² - τ²) 需要 k² > κ²+τ²
k2 = k_test**2
print(f"    k² = {mp.nstr(k2, 6)} m⁻²")
print(f"    κ²+τ² = {mp.nstr(s2, 6)} m⁻²")
print(f"    k²/(κ²+τ²) = {mp.nstr(k2/s2, 4)}")
if k2 > s2:
    omega_framework = c * sqrt(k2 - s2)
    print(f"    ω_std = {mp.nstr(omega_std, 6)} rad/s")
    print(f"    ω_framework = {mp.nstr(omega_framework, 6)} rad/s")
    correction = (omega_std - omega_framework)/omega_std*100
    print(f"    修正: {mp.nstr(correction, 4)} %")
    # 相速度
    v_phase = omega_framework / k_test
    print(f"    相速度: v_phase/c = {mp.nstr(v_phase/c, 12)}")
else:
    print(f"    k² < κ²+τ² → ω² < 0 (快子), 此 k 无物理意义")
    print(f"    框架中此色散关系不适用于光子 (光子 κ=τ=0)")

# 结论: 对光子 (κ_γ=0), 无色散修正
# 对有质量粒子, 色散关系就是标准相对论关系
# 框架内无额外色散修正 → 无 PRED 级预言
print(f"\n  [结论] 框架色散关系 = 标准相对论色散关系")
print(f"    光子 κ=τ=0 → 无修正")
print(f"    电子 κ,τ 给出 ω² = c²k² + (m_e c²/ℏ)²")
print(f"    无额外色散修正 → 无 PRED 级预言")

