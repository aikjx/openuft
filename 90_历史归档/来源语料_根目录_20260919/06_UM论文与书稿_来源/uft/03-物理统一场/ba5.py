S_ratio = S_dS/S_BH
print('S_dS = %.6e' % S_dS)
print('S_BH = %.6e' % S_BH)
print('S_ratio = %.6e' % S_ratio)
print('log10(S_ratio) = %.4f' % (mp.log(S_ratio)/mp.log(10)))
print()
