# 光线偏折
# ============================================================

print("\n【光线偏折（引力透镜）】")

# 光线偏折角: α = 4GM/(c²b) = kM/(πc²b)
# 太阳的光线偏折
M_sun_test = M_sun
b_sun = R_sun  # 碰撞参数等于太阳半径
alpha_trad = 4 * G * M_sun_test / (c**2 * b_sun)
alpha_k = k * M_sun_test / (mp.pi * c**2 * b_sun)
alpha_arcsec = alpha_trad * (180/mp.pi) * 3600

