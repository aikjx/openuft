def main():
    txt = io.open(RD, encoding="utf-8").read()
    os.makedirs(os.path.dirname(BAK), exist_ok=True)
    if not os.path.exists(BAK):
        shutil.copy2(RD, BAK)
        print("备份已建：", BAK)
    else:
        print("备份已存在，不覆盖：", BAK)

    anchor = "TUFT-%s_" % RID
    exists = txt.count(anchor)
    print("注册前锚点计数（%s）= %d" % (anchor, exists))
    if exists > 0:
        print("本卷条目已存在 ⇒ 幂等跳过，不重复插入。")
        return 0

    lines = txt.split("\n")
    out = []
    done = {"src": 0, "jud": 0, "compact": 0, "full": 0}
    i = 0
    while i < len(lines):
        ln = lines[i]
        out.append(ln)
        # ①src 树：插在 r290 源码条目之后（锚点串含他卷 RID，不污染本卷）
        if ln.startswith("│   ├── TUFT-r290_") and ".py" in ln:
            out.append(L_SRC)
            done["src"] += 1
        # ②jud 树：插在最后一条判定册之后
        elif ln.startswith("├── 判定_TUFT-r287_"):
            out.append(L_JUD)
            done["jud"] += 1
        # ③compact 章：插在 r289 compact 条目之后（该行含 r292 之外的 r289 锚）
        elif ln.startswith("- **r289（2026-10-31）"):
            out.append(L_COMPACT)
            done["compact"] += 1
        i += 1
    # ④full 章：追加到文件末尾
    if done["compact"] == 1:
        out.append(L_FULL.rstrip("\n"))
        done["full"] += 1

    new = "\n".join(out)
    io.open(RD, "w", encoding="utf-8").write(new)
    print("插入统计：", done)

    # ---- 从磁盘读回，逐 RID 固定串清点
    back = io.open(RD, encoding="utf-8").read()
    for key in ["TUFT-%s_" % RID, "判定_TUFT-%s_" % RID, "### %s ·" % RID, "- **%s（" % RID]:
        print("清点 %-22s = %d" % (key, back.count(key)))

    # ---- diff 零删除守卫
    old = io.open(BAK, encoding="utf-8").read().split("\n")
    cur = back.split("\n")
    co, cc = Counter(old), Counter(cur)
    lost = [k for k in co if cc[k] < co[k]]
    print("删除行检查：备份 %d 行 → 新版 %d 行；丢失行种类 %d" % (len(old), len(cur), len(lost)))
    if lost:
        for k in lost[:5]:
            print("  !! 丢失：", k[:120])
    print("RC =", 0 if not lost and all(v == 1 for v in done.values()) else 2)
    return 0 if not lost else 2


if __name__ == "__main__":
    raise SystemExit(main())
