# 实际计算相互作用能
print('【2.2 数值积分: V(α)】')

def interaction_energy(alpha, R, b_steps=100):
    """
    计算两个对称螺旋的相互作用能
    alpha: 螺旋的 α = b/(2πR)
    R: 螺旋半径
    """
    b = 2 * math.pi * R * alpha
    mu0 = 4 * math.pi * 1e-7  # μ₀
    
    # 积分 (用复化 Simpson 或梯形法)
    phi_vals = np.linspace(-np.pi, np.pi, b_steps)
    dphi = phi_vals[1] - phi_vals[0]
    
    integrand = np.zeros_like(phi_vals)
    for i, phi in enumerate(phi_vals):
        cos_phi = np.cos(phi)
        sin_half = np.sin(phi/2)
        r12 = np.sqrt(4*R**2 * sin_half**2 + (b*phi/(2*math.pi))**2)
        if r12 < 1e-30:
            r12 = 1e-30
        dr_dot = R**2 * cos_phi - (b/(2*math.pi))**2
        integrand[i] = dr_dot / r12
    
    V = -mu0 * e_charge**2 / (4*math.pi) * np.trapezoid(integrand, phi_vals)
    return V

