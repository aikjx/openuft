"""Run only when playwright and Chromium available. 100% offline page.set_content."""
import json,pathlib
P=pathlib.Path(__file__).resolve().parents[1]
from playwright.sync_api import sync_playwright
result={'checks':[],'page_errors':[],'console_errors':[],'rendering':'Canvas2D browser visualization; not laboratory experiment'}

def ck(name,condition):result['checks'].append([name,bool(condition)])

with sync_playwright() as p:
 browser=p.chromium.launch(headless=True,executable_path='/usr/bin/chromium',args=['--no-sandbox','--disable-dev-shm-usage'])
 page=browser.new_page(viewport={'width':1380,'height':960},device_scale_factor=1)
 page.on('pageerror',lambda e:result['page_errors'].append(str(e)))
 page.on('console',lambda x:result['console_errors'].append(x.text) if x.type=='error' else None)
 page.set_content((P/'web/index.html').read_text(encoding='utf-8'),wait_until='load')
 page.wait_for_timeout(150)
 ck('title',page.title().startswith('ROOT V76'))
 ck('five tabs',page.locator('.tab').count()==5)
 ck('four canvases',page.locator('canvas').count()==4)
 ck('metric initialized',page.locator('#u_total').inner_text()!='—')
 ck('default angle 60',page.locator('#anglev').inner_text()=='60°')
 page.locator('#angle').fill('0');page.wait_for_timeout(70)
 ck('0-degree cross positive',float(page.locator('#u_cross').inner_text())>0)
 page.locator('#angle').fill('180');page.wait_for_timeout(70)
 ck('180-degree cancellation',page.locator('#u_total').inner_text()=='0')
 page.locator('button[data-target="ledger"]').click()
 ck('ledger tab visible',page.locator('#ledger').evaluate('(e)=>getComputedStyle(e).display')!='none')
 ck('closed ledger constant 1 GJ',page.locator('#ledger_total').inner_text()=='1.0000')
 page.locator('#frac').fill('100')
 ck('battery becomes zero',page.locator('#ledger_battery').inner_text()=='0.0000')
 ck('field becomes 1 GJ',page.locator('#ledger_field').inner_text()=='1.0000')
 page.locator('button[data-target="quantum"]').click()
 page.locator('#phase').fill('180')
 ck('phase 180 lower energy',float(page.locator('#qenergy').inner_text())<1.5)
 page.locator('#qcouple').fill('0')
 ck('zero quantum coupling phase independent',page.locator('#qenergy').inner_text()=='1.5000')
 page.locator('button[data-target="helix"]').click()
 page.locator('#lambda').fill('0')
 ck('helix torsion zero',page.locator('#htorsion').inner_text()=='0.00000')
 page.locator('#lambda').fill('45')
 ck('helix torsion nonzero',float(page.locator('#htorsion').inner_text())>0)
 page.locator('button[data-target="catalog"]').click()
 ck('proof table shows G open',page.locator('#catalog').get_by_text('尚无无参数推导').count()>0)
 page.locator('button[data-target="em"]').click();page.locator('#angle').fill('60')
 page.screenshot(path=str(P/'results'/'ROOT_V76_网页实际运行截图.png'),full_page=True)
 browser.close()
result['passed']=sum(1 for x in result['checks'] if x[1]);result['total']=len(result['checks'])
(P/'results'/'browser_smoke.json').write_text(json.dumps(result,ensure_ascii=False,indent=2),encoding='utf-8')
print(json.dumps(result,ensure_ascii=False,indent=2))
if result['passed']!=result['total'] or result['page_errors'] or result['console_errors']:raise SystemExit(2)
